func TestReleaseGrammarRuleTable(t *testing.T) {
	if len(grammarRuleRows) != 309 {
		t.Fatalf("table has %d rows", len(grammarRuleRows))
	}
	for _, r := range grammarRuleRows {
		typ, le := gParse(gProfile(r.ver, r.features...), r.expr)
		switch {
		case r.category == "" && le != nil:
			t.Errorf("%s %s %q: rejected: %s: %s", r.ver, r.id, r.expr, le.Category, le.SafeMessage)
		case r.category == "" && typ != r.typ:
			t.Errorf("%s %s %q: type %q want %q", r.ver, r.id, r.expr, typ, r.typ)
		case r.category != "" && le == nil:
			t.Errorf("%s %s %q: accepted as %q", r.ver, r.id, r.expr, typ)
		case r.category != "" && le.Category != r.category:
			t.Errorf("%s %s %q: category %q want %q (%s)", r.ver, r.id, r.expr, le.Category, r.category, le.SafeMessage)
		}
	}
}

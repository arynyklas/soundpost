// Observations at one instant divide zero by zero: the reference result is the
// hardware NaN with the sign bit set (mx-0033: host a at t=6s has three
// observations at 5s).
func TestRateCounterSingleInstantIsNegativeQuietNaN(t *testing.T) {
	row := variantHostRow(1, 5e9, 3, "a", "n=555")
	plan := metricPlan(t, `rate_counter({app="api"}|logfmt|unwrap n[5s])`, value.Evaluation{Instant: true, Time: 6e9})
	account := value.NewBoundedAccount(32 << 20)
	r, _, err := Evaluate(context.Background(), plan, &metricSource{rows: []scan.LogRow{row}}, account)
	if err != nil || len(r.Vector) != 1 {
		t.Fatalf("err=%v vector=%v", err, r.Vector)
	}
	if bits := uint64(r.Vector[0].Samples[0].Float); bits != 0xfff8000000000000 {
		t.Fatalf("bits=%016x want fff8000000000000", bits)
	}
	account.Release(value.ResultBytes(r))
}

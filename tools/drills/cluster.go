// This file is the shared real-cluster driver of the node-loss and pause drills. It starts the
// PRODUCED static binary three times as `serve --mode=distributed` with mTLS between the members,
// bootstraps one installation exactly like tools/smoke/install_distributed.go (single bootstrap,
// seed export, node files generated by internal/config), ingests through the public ingest API
// with the bootstrapped source credential and reads back through the PromQL query API. Everything
// here is prefixed dc so it cannot collide with the other drill files of the same package.

// dcMetric is the metric every drill batch carries. Each batch is ONE record with ONE series
// (label batch=<batch id>) and a unique float value, so every acknowledged id can be read back
// individually and its exact semantic data (id, value bits) compared.
const dcMetric = "drill_writes"

// dcPoolSize is how many distinct batch ids (series) one installation can carry: it is the number
// of label values declared in the drill source's policy and stays below its MaxSeries of 1000.
const dcPoolSize = 700

// Linux signal numbers. They are numeric constants (not syscall.SIGSTOP) so the package still
// compiles on a developer's Windows host; the drills themselves only run on Linux.
const (
	dcSigStop = syscall.Signal(19)
	dcSigCont = syscall.Signal(18)
)

// ---- pure verifiers (unit-tested) ----

// dcDigest is the digest of the semantic data of one drill batch: which id and which exact float
// bits. The ledger side and the read-back side both use it.
func dcDigest(id string, bits uint64) string {
	sum := sha256.Sum256([]byte("soundpost.drill/v1\x00" + dcMetric + "\x00" + id + "\x00" + fmt.Sprintf("%016x", bits)))
	return hex.EncodeToString(sum[:])
}

// dcBatchSemantics extracts what a reader must be able to retrieve from a drill batch and
// returns its id and digest. A batch that is not exactly one drill record is an error.
func dcBatchSemantics(b model.Batch) (string, string, error) {
	if len(b.Records) != 1 || b.Records[0].Payload.Metric == nil {
		return "", "", errors.New("a drill batch is exactly one metric record")
	}
	m := b.Records[0].Payload.Metric
	if m.Name != dcMetric || m.Value == nil || len(m.Labels) != 1 || m.Labels[0].Name != "batch" {
		return "", "", errors.New("a drill batch carries one float sample with the single label batch")
	}
	if m.Labels[0].Value != b.ID.String() {
		return "", "", errors.New("the batch label must be the batch id")
	}
	return b.ID.String(), dcDigest(b.ID.String(), uint64(*m.Value)), nil
}

// dcCompleteVector decodes a query response and returns its instant-vector elements only when the
// answer is a COMPLETE one: one project, no failure, complete, a vector.
func dcCompleteVector(raw []byte) ([]query.VectorElement, error) {
	var result query.Result
	if err := json.Unmarshal(raw, &result); err != nil {
		return nil, errors.New("answer is not a query result")
	}
	if len(result.Projects) != 1 {
		return nil, errors.New("answer does not carry exactly one project")
	}
	p := result.Projects[0]
	if p.Failure != nil {
		return nil, errors.New("answer carries a typed failure")
	}
	if p.Completeness != query.CompletenessComplete {
		return nil, errors.New("answer is not complete")
	}
	if p.Value == nil || p.Value.Type != query.ValueVector {
		return nil, errors.New("answer is not an instant vector")
	}
	return p.Value.Vector, nil
}

// dcElementID returns the batch id of one read-back series, which must carry exactly the batch label
// (what the batch carried) and a float sample. last_over_time keeps the metric name as a label
// (withName); count_over_time drops it.
func dcElementID(e query.VectorElement, withName bool) (string, error) {
	labels := e.Labels
	if withName {
		if len(labels) == 0 || labels[0].Name != "__name__" || labels[0].Value != dcMetric {
			return "", fmt.Errorf("series does not carry the label __name__=%s", dcMetric)
		}
		labels = labels[1:]
	}
	if len(labels) != 1 || labels[0].Name != "batch" || labels[0].Value == "" {
		names := make([]string, 0, len(e.Labels))
		for _, l := range e.Labels {
			names = append(names, dcSafeToken(l.Name))
		}
		return "", fmt.Errorf("series carries labels %v, want exactly the batch label", names)
	}
	if e.Sample.Float == nil {
		return "", errors.New("series sample is not a float")
	}
	return labels[0].Value, nil
}

// dcVectorDigests turns a complete instant-vector answer of last_over_time(drill_writes[..]) into
// batch id -> digest of the data actually read back. Two series for one id, a series without the
// batch label or a non-float sample are errors: the read back must be exactly the written data.
func dcVectorDigests(raw []byte) (map[string]string, error) {
	vector, err := dcCompleteVector(raw)
	if err != nil {
		return nil, err
	}
	out := make(map[string]string, len(vector))
	for _, e := range vector {
		id, err := dcElementID(e, true)
		if err != nil {
			return nil, err
		}
		if _, dup := out[id]; dup {
			return nil, fmt.Errorf("batch %s is read back twice", id)
		}
		out[id] = dcDigest(id, uint64(*e.Sample.Float))
	}
	return out, nil
}

// dcSampleCounts turns count_over_time(drill_writes[..]) into batch id -> number of stored samples.
func dcSampleCounts(raw []byte) (map[string]uint64, error) {
	vector, err := dcCompleteVector(raw)
	if err != nil {
		return nil, err
	}
	out := make(map[string]uint64, len(vector))
	for _, e := range vector {
		id, err := dcElementID(e, false)
		if err != nil {
			return nil, err
		}
		f := math.Float64frombits(uint64(*e.Sample.Float))
		if f < 0 || f != math.Trunc(f) || f > 1<<53 {
			return nil, fmt.Errorf("batch %s has a non-count sample count", id)
		}
		if _, dup := out[id]; dup {
			return nil, fmt.Errorf("batch %s is counted twice", id)
		}
		out[id] = uint64(f)
	}
	return out, nil
}

// dcVerifyCounts requires every acknowledged id to be stored exactly once: a retry must not
// duplicate data.
func dcVerifyCounts(counts map[string]uint64, acks []Ack) error {
	var bad []string
	for _, a := range acks {
		if n := counts[a.ID]; n != 1 {
			bad = append(bad, fmt.Sprintf("%s=%d", a.ID, n))
		}
	}
	if len(bad) > 0 {
		sort.Strings(bad)
		return fmt.Errorf("acknowledged ids not stored exactly once: %v", bad)
	}
	return nil
}

// dcUnknownRetained returns retained ids that this drill never issued (data that does not belong
// to any batch it sent).
func dcUnknownRetained(retained map[string]string, issued map[string]bool) []string {
	var out []string
	for id := range retained {
		if !issued[id] {
			out = append(out, id)
		}
	}
	sort.Strings(out)
	return out
}

// dcIdenticalMembers requires every member to retain exactly the same ids with the same digest.
func dcIdenticalMembers(members map[uint64]map[string]string) error {
	var ids []uint64
	for id := range members {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
	for _, id := range ids[1:] {
		a, b := members[ids[0]], members[id]
		if len(a) != len(b) {
			return fmt.Errorf("member %d retains %d ids, member %d retains %d", ids[0], len(a), id, len(b))
		}
		for k, v := range a {
			if b[k] != v {
				return fmt.Errorf("member %d and member %d retain %s differently", ids[0], id, k)
			}
		}
	}
	return nil
}

// dcVerdict is the classification of one ingest attempt.
type dcVerdict string

const (
	dcAcked        dcVerdict = "acked"         // 200 with a receipt for exactly this batch
	dcTypedRefusal dcVerdict = "typed_refusal" // 503 with the typed retryable fault body
	dcTransport    dcVerdict = "transport"     // no HTTP answer (refused, reset, timeout)
	dcRejected     dcVerdict = "rejected"      // any other HTTP answer: not retryable
	dcMalformed    dcVerdict = "malformed"     // 200 without a usable receipt, 503 without a typed body
)

// dcRefusalCodes are the typed fault codes a quorum-less member may answer with (HTTP 503).
var dcRefusalCodes = map[string]bool{"unavailable": true, "timeout": true, "stale": true}

var dcTokenPattern = regexp.MustCompile(`^[a-z_]{1,32}$`)

// dcSafeToken keeps only a closed lower-case token so a body never reaches a report.
func dcSafeToken(s string) string {
	if dcTokenPattern.MatchString(s) {
		return s
	}
	return "unknown"
}

// dcClassifyIngest classifies one attempt from the transport error, the HTTP status and body. It
// returns the receipt when the attempt was acknowledged and a short, secret-free detail.
func dcClassifyIngest(status int, body []byte, transportErr error, want model.ID) (dcVerdict, string, model.Receipt) {
	var none model.Receipt
	if transportErr != nil {
		return dcTransport, dcTransportClass(transportErr), none
	}
	switch status {
	case 200:
		var r model.Receipt
		if json.Unmarshal(body, &r) != nil || r.BatchID != want || r.Cursor.Index == 0 || r.Cursor.Group == (model.ID{}) {
			return dcMalformed, "status_200_without_receipt_for_this_batch", none
		}
		return dcAcked, "status_200", r
	case 503:
		var f struct {
			Code      string `json:"code"`
			Retryable bool   `json:"retryable"`
		}
		if json.Unmarshal(body, &f) != nil || !f.Retryable || !dcRefusalCodes[f.Code] {
			return dcMalformed, "status_503_without_typed_retryable_fault", none
		}
		return dcTypedRefusal, "status_503_" + f.Code, none
	default:
		var f struct {
			Code string `json:"code"`
		}
		_ = json.Unmarshal(body, &f)
		return dcRejected, "status_" + strconv.Itoa(status) + "_" + dcSafeToken(f.Code), none
	}
}

// dcTransportClass names the class of a transport error without printing the error text.
func dcTransportClass(err error) string {
	var ne net.Error
	switch {
	case errors.Is(err, syscall.ECONNREFUSED):
		return "connection_refused"
	case errors.Is(err, syscall.ECONNRESET):
		return "connection_reset"
	case errors.Is(err, io.EOF), errors.Is(err, io.ErrUnexpectedEOF):
		return "eof"
	case errors.As(err, &ne) && ne.Timeout():
		return "timeout"
	default:
		return "transport_error"
	}
}

// dcServedComplete reports whether a query answer is a COMPLETE read (200, no failure, complete).
// A member that cannot prove its read must answer anything else.
func dcServedComplete(status int, raw []byte, transportErr error) (bool, string) {
	if transportErr != nil {
		return false, dcTransportClass(transportErr)
	}
	if status != 200 {
		var f struct {
			Code string `json:"code"`
		}
		_ = json.Unmarshal(raw, &f)
		return false, "status_" + strconv.Itoa(status) + "_" + dcSafeToken(f.Code)
	}
	if _, err := dcCompleteVector(raw); err != nil {
		return false, err.Error()
	}
	return true, "complete"
}

// dcSent is one HTTP attempt of one batch: what was sent (a hash of the exact body) and the
// verdict.
type dcSent struct {
	ID       string
	Member   uint64
	BodyHash string
	Verdict  dcVerdict
}

// dcVerifyRetries requires every batch whose attempt did not succeed to have been retried
// UNCHANGED (one body hash across all its attempts) until it was acknowledged.
func dcVerifyRetries(sent []dcSent, acks []Ack) error {
	acked := map[string]bool{}
	for _, a := range acks {
		acked[a.ID] = true
	}
	hash := map[string]string{}
	failed := map[string]bool{}
	for _, s := range sent {
		if h, ok := hash[s.ID]; ok && h != s.BodyHash {
			return fmt.Errorf("batch %s was retried with a different body", s.ID)
		}
		hash[s.ID] = s.BodyHash
		if s.Verdict != dcAcked {
			failed[s.ID] = true
		}
	}
	for id := range failed {
		if !acked[id] {
			return fmt.Errorf("batch %s was refused and never retried to an acknowledgement", id)
		}
	}
	return nil
}

// dcAckTime is when one acknowledged attempt started and when it completed.
type dcAckTime struct {
	ID      string
	Member  uint64
	Started time.Time
	At      time.Time
}

// dcFirstAckAfter is the latency from `after` to the first acknowledgement of a request that was
// STARTED after `after` (an in-flight request that happened to finish after the fault does not
// count: it proves nothing about the cluster's behaviour with the member down).
func dcFirstAckAfter(times []dcAckTime, after time.Time) (time.Duration, bool) {
	var best time.Time
	for _, t := range times {
		if t.Started.After(after) && (best.IsZero() || t.At.Before(best)) {
			best = t.At
		}
	}
	if best.IsZero() {
		return 0, false
	}
	return best.Sub(after), true
}

// dcAcksBetween counts acknowledgements completed in (from, to]; a zero `to` means no upper bound.
func dcAcksBetween(times []dcAckTime, from, to time.Time) int {
	n := 0
	for _, t := range times {
		if t.At.After(from) && (to.IsZero() || !t.At.After(to)) {
			n++
		}
	}
	return n
}

// dcAcksStartedAfter counts acknowledged requests that were STARTED after t.
func dcAcksStartedAfter(times []dcAckTime, t time.Time) int {
	n := 0
	for _, a := range times {
		if a.Started.After(t) {
			n++
		}
	}
	return n
}

// dcProcState parses the state letter of /proc/<pid>/stat ("T" is stopped).
func dcProcState(stat string) (byte, error) {
	i := strings.LastIndexByte(stat, ')')
	if i < 0 || i+2 >= len(stat) {
		return 0, errors.New("unparsable /proc stat")
	}
	return stat[i+2], nil
}

// dcSameCursor reports whether `want` members all report the same applied index.
func dcSameCursor(cursors map[uint64]uint64, want int) bool {
	if len(cursors) != want || want == 0 {
		return false
	}
	var first uint64
	set := false
	for _, v := range cursors {
		if !set {
			first, set = v, true
		} else if v != first {
			return false
		}
	}
	return true
}

// ---- HTTPS client ----

type dcFailure struct {
	Stage, Code string
	Status      int
}

func (f *dcFailure) Error() string {
	if f.Status != 0 {
		return fmt.Sprintf("%s: %s (status %d)", f.Stage, f.Code, f.Status)
	}
	return f.Stage + ": " + f.Code
}

type dcSite struct {
	base   string
	cert   *x509.Certificate
	client *http.Client
}

func newDCSite(base string, cert *x509.Certificate, timeout time.Duration) *dcSite {
	pool := x509.NewCertPool()
	pool.AddCert(cert)
	jar, _ := cookiejar.New(nil)
	return &dcSite{base: base, cert: cert, client: &http.Client{Transport: &http.Transport{TLSClientConfig: &tls.Config{RootCAs: pool, MinVersion: tls.VersionTLS13}, DisableKeepAlives: true}, Jar: jar, Timeout: timeout,
		CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}}
}

// withTimeout returns a view of the same site (same cookie jar) with another request timeout.
func (s *dcSite) withTimeout(d time.Duration) *dcSite {
	c := *s.client
	c.Timeout = d
	return &dcSite{base: s.base, cert: s.cert, client: &c}
}

func (s *dcSite) get(path string) (int, []byte, error) {
	req, err := http.NewRequest("GET", s.base+path, nil)
	if err != nil {
		return 0, nil, err
	}
	resp, err := s.client.Do(req)
	if err != nil {
		return 0, nil, err
	}
	defer resp.Body.Close()
	raw, err := io.ReadAll(io.LimitReader(resp.Body, 8<<20))
	return resp.StatusCode, raw, err
}

func (s *dcSite) post(path string, body any, csrf, bearer string) (int, []byte, error) {
	raw, err := json.Marshal(body)
	if err != nil {
		return 0, nil, err
	}
	return s.postRaw(path, raw, csrf, bearer)
}

func (s *dcSite) postRaw(path string, raw []byte, csrf, bearer string) (int, []byte, error) {
	req, err := http.NewRequest("POST", s.base+path, bytes.NewReader(raw))
	if err != nil {
		return 0, nil, err
	}
	req.Header.Set("Content-Type", "application/json")
	client := s.client
	if bearer != "" {
		req.Header.Set("Authorization", "Bearer "+bearer)
		c := *client
		c.Jar = nil
		client = &c
	} else {
		req.Header.Set("Origin", s.base)
		req.Header.Set("X-CSRF-Token", csrf)
	}
	resp, err := client.Do(req)
	if err != nil {
		return 0, nil, err
	}
	defer resp.Body.Close()
	out, err := io.ReadAll(io.LimitReader(resp.Body, 8<<20))
	return resp.StatusCode, out, err
}


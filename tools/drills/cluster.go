type dcFixture struct {
	org, project, source        model.ID
	credential                  string
	readerEmail                 string
	service, environment, build model.ID
	pool                        []model.ID // batch ids declared in the source policy's label allow-list
}

const dcReaderPassword = "drills reader password 2026"

func dcRequire(stage string, status, want int, err error) error {
	if err != nil {
		return &dcFailure{Stage: stage, Code: dcTransportClass(err)}
	}
	if status != want {
		return &dcFailure{Stage: stage, Code: "unexpected_status", Status: status}
	}
	return nil
}

// dcBootstrap performs the single-installation bootstrap over HTTPS exactly like the install
// smoke: owner, organization, project, reader, grant and one onboarded source with its credential.
func dcBootstrap(site *dcSite, token string) (*dcFixture, error) {
	fx := &dcFixture{}
	const ownerPassword = "drills owner password 2026"
	status, raw, err := site.post("/api/v1/bootstrap", map[string]string{"Token": token, "Email": "owner@drills.invalid", "Password": ownerPassword}, "", "")
	if err = dcRequire("bootstrap", status, 200, err); err != nil {
		return nil, err
	}
	var owner auth.Session
	if err = json.Unmarshal(raw, &owner); err != nil {
		return nil, err
	}
	fx.org, fx.project, fx.source = model.NewID(), model.NewID(), model.NewID()
	admin := func(kind string, p auth.AdminPayload) error {
		status, raw, err := site.post("/api/v1/admin/read", struct {
			Kind string `json:"kind"`
		}{"organizations"}, owner.CSRF, "")
		if err = dcRequire("admin_read", status, 200, err); err != nil {
			return err
		}
		var view auth.AdminView
		if err = json.Unmarshal(raw, &view); err != nil {
			return err
		}
		p.Reason = "failure drills"
		payload, _ := json.Marshal(p)
		status, _, err = site.post("/api/v1/admin/commands", auth.AdminCommandRequest{CommandID: model.NewID(), ExpectedRevision: view.Revision, OrgID: fx.org, Kind: kind, Payload: payload}, owner.CSRF, "")
		return dcRequire("admin_"+kind, status, 200, err)
	}
	reader := model.NewID()
	fx.readerEmail = "reader@drills.invalid"
	for _, step := range []struct {
		kind string
		p    auth.AdminPayload
	}{
		{"create_org", auth.AdminPayload{Name: "failure drills"}},
		{"create_project", auth.AdminPayload{ID: fx.project, Name: "failure drills"}},
		{"create_user", auth.AdminPayload{ID: reader, Email: fx.readerEmail, Password: dcReaderPassword}},
		{"membership", auth.AdminPayload{UserID: reader, Enabled: true}},
		{"grant", auth.AdminPayload{UserID: reader, ProjectID: fx.project, Enabled: true, Permissions: []string{string(auth.Read)}}},
	} {
		if err = admin(step.kind, step.p); err != nil {
			return nil, err
		}
	}
	fx.service, fx.environment, fx.build = model.NewID(), model.NewID(), model.NewID()
	// The source policy admits label values only from an explicit allow-list, so every batch id the
	// drill can ever send is declared up front; one batch id is one series.
	batchLabels := make([]string, dcPoolSize)
	for i := range batchLabels {
		id := model.NewID()
		fx.pool = append(fx.pool, id)
		batchLabels[i] = id.String()
	}
	var approved model.Scalar
	_ = json.Unmarshal([]byte(`503`), &approved)
	policy := model.SourcePolicy{Revision: 1, Enabled: true, Class: "structured", Kinds: []model.Kind{model.Metric, model.Log, model.ErrorKind, model.SpanKind},
		Resources:     model.ResourceRegistry{Services: []model.ID{fx.service}, Environments: []model.ID{fx.environment}, Builds: []model.ID{fx.build}, Instances: []string{"instance"}},
		Templates:     []model.LogTemplate{{ID: "failed", Revision: 1, Line: "operation failed: {status}", Severity: "error", Fields: []model.TemplateField{{Name: "status", Type: "int64", MaxBytes: 16, Sensitivity: "metadata", Values: []model.Scalar{approved}}}}},
		Operations:    []string{"operation"},
		Labels:        map[string][]string{"batch": batchLabels},
		RetentionDays: map[model.Kind]uint32{model.Metric: 30, model.Log: 14, model.ErrorKind: 30, model.SpanKind: 14}, MaxBytes: 1 << 30, MaxSeries: 1000}
	status, raw, err = site.post("/api/v1/sources", auth.SourceOnboarding{CommandID: model.NewID(), Org: fx.org, Project: fx.project, Source: fx.source, Expires: model.UnixNano(time.Now().Add(6 * time.Hour).UnixNano()), Policy: policy, Reason: "failure drills"}, owner.CSRF, "")
	if err = dcRequire("source_onboard", status, 200, err); err != nil {
		return nil, err
	}
	var issued auth.SourceOnboarded
	if err = json.Unmarshal(raw, &issued); err != nil {
		return nil, err
	}
	fx.credential = issued.Credential
	return fx, nil
}

// ---- PKI ----

type dcMember struct {
	id       uint64
	name     string
	identity string
}

var dcMembers = []dcMember{{1, "a", "node-a"}, {2, "b", "node-b"}, {3, "c", "node-c"}}

// dcPKI writes a throwaway cluster CA and one certificate per member. Each certificate carries the
// member's URI SAN spiffe://soundpost/node/<identity> and loopback dial names.
func dcPKI(dir string) (ca string, certs, keys map[uint64]string, err error) {
	caKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return
	}
	now := time.Now()
	authority := &x509.Certificate{SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: "Soundpost failure drills CA"}, NotBefore: now.Add(-time.Minute), NotAfter: now.Add(6 * time.Hour), IsCA: true, BasicConstraintsValid: true, KeyUsage: x509.KeyUsageCertSign | x509.KeyUsageDigitalSignature}
	der, err := x509.CreateCertificate(rand.Reader, authority, authority, &caKey.PublicKey, caKey)
	if err != nil {
		return
	}
	ca = filepath.Join(dir, "ca.pem")
	if err = os.WriteFile(ca, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o600); err != nil {
		return
	}
	certs, keys = map[uint64]string{}, map[uint64]string{}
	for _, n := range dcMembers {
		var private *ecdsa.PrivateKey
		if private, err = ecdsa.GenerateKey(elliptic.P256(), rand.Reader); err != nil {
			return
		}
		identity, _ := url.Parse("spiffe://soundpost/node/" + n.identity)
		leaf := &x509.Certificate{SerialNumber: big.NewInt(int64(n.id + 1)), Subject: pkix.Name{CommonName: "failure drill node"}, NotBefore: now.Add(-time.Minute), NotAfter: now.Add(6 * time.Hour), DNSNames: []string{"localhost"}, IPAddresses: []net.IP{net.ParseIP("127.0.0.1")}, URIs: []*url.URL{identity}, KeyUsage: x509.KeyUsageDigitalSignature, ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth, x509.ExtKeyUsageClientAuth}}
		var raw []byte
		if raw, err = x509.CreateCertificate(rand.Reader, leaf, authority, &private.PublicKey, caKey); err != nil {
			return
		}
		encoded, e := x509.MarshalPKCS8PrivateKey(private)
		if e != nil {
			err = e
			return
		}
		certs[n.id], keys[n.id] = filepath.Join(dir, n.name+".pem"), filepath.Join(dir, n.name+".key")
		if err = os.WriteFile(certs[n.id], pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: raw}), 0o600); err != nil {
			return
		}
		if err = os.WriteFile(keys[n.id], pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: encoded}), 0o600); err != nil {
			return
		}
	}
	return
}

func dcFreeAddress() (string, error) {
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return "", err
	}
	defer l.Close()
	return l.Addr().String(), nil
}

// dcLog keeps the first MiB of a process's output for liveness diagnostics. It is never written to
// a report: a report carries ids, digests and statuses only. With SOUNDPOST_DRILL_LOG_DIR set the
// output is also appended to <dir>/<name>.log, a debugging aid for a drill developer that a run
// for evidence leaves unset.
type dcLog struct {
	mu     sync.Mutex
	b      bytes.Buffer
	tee    *os.File
	reason string // last closed reason token printed by the current incarnation (reset at each start)
}

func newDCLog(name string) *dcLog {
	l := &dcLog{}
	if dir := os.Getenv("SOUNDPOST_DRILL_LOG_DIR"); dir != "" {
		if f, err := os.OpenFile(filepath.Join(dir, name+".log"), os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o600); err == nil {
			l.tee = f
		}
	}
	return l
}

func (s *dcLog) Write(p []byte) (int, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if m := dcExitReason.FindAllSubmatch(p, -1); len(m) > 0 {
		s.reason = string(m[len(m)-1][1])
	}
	if s.b.Len() < 1<<20 {
		s.b.Write(p)
	}
	if s.tee != nil {
		_, _ = s.tee.Write(p)
	}
	return len(p), nil
}

// dcExitReason matches the one closed reason token soundpost serve prints when it refuses or fail-stops
// (`(reason=<code>)` or `reason=<code> `); nothing else of the output is read.
var dcExitReason = regexp.MustCompile(`reason=([a-z][a-z0-9_]{0,63})`)

// newIncarnation forgets the reason of the previous process of this member.
func (s *dcLog) newIncarnation() {
	s.mu.Lock()
	s.reason = ""
	s.mu.Unlock()
}

// lastReason is the last closed reason token the current incarnation printed, or "".
func (s *dcLog) lastReason() string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.reason
}

// ---- the three-process cluster ----

type dcProc struct {
	cmd  *exec.Cmd
	done chan struct{} // closed when the process has exited
}

// dcCluster is a real three-member mTLS cluster of the produced binary on loopback, all state under
// env.Work (an allowlisted isolated root).
type dcCluster struct {
	opts   dcOptions
	link   *dcNet
	disks  map[uint64]*dcDisk
	dial   map[uint64]string // the address the other members dial (peer, or its proxy)
	env    *Env
	binary string
	work   string
	seed   string
	cfg    config.InstallConfig
	public map[uint64]string
	peer   map[uint64]string
	data   map[uint64]string
	logs   map[uint64]*dcLog
	fx     *dcFixture

	mu       sync.Mutex
	procs    map[uint64]*dcProc
	sites    map[uint64]*dcSite
	sessions map[uint64]auth.Session
	down     map[uint64]bool // killed or paused: known not to answer
	retired  map[uint64]bool // refused to rejoin and left out for the rest of the drill
	quit     chan struct{}
	quitOnce sync.Once
}

// dcOptions selects the failure machinery a drill needs beyond plain processes.
type dcOptions struct {
	proxy  bool // peer traffic runs through the drill's own proxies (link-level partitions)
	inject bool // members run under the storage fault injector (fsync failure, power loss, vanishing disk)
}

// newDCCluster is newDCClusterWith with no extra machinery.
func newDCCluster(env *Env) (*dcCluster, error) { return newDCClusterWith(env, dcOptions{}) }

// newDCClusterWith lays out the PKI, the typed configuration and the data directories and APPROVES
// every directory and loopback address against the allowlist before anything is created.
func newDCClusterWith(env *Env, opts dcOptions) (*dcCluster, error) {
	if env.Binary == "" {
		return nil, errors.New("this drill needs --binary (the produced static soundpost binary)")
	}
	binary, err := filepath.Abs(env.Binary)
	if err != nil {
		return nil, err
	}
	c := &dcCluster{env: env, binary: binary, work: env.Work, public: map[uint64]string{}, peer: map[uint64]string{}, dial: map[uint64]string{}, data: map[uint64]string{}, opts: opts, disks: map[uint64]*dcDisk{},
		logs: map[uint64]*dcLog{}, procs: map[uint64]*dcProc{}, sites: map[uint64]*dcSite{}, sessions: map[uint64]auth.Session{}, down: map[uint64]bool{}, quit: make(chan struct{})}
	pki := filepath.Join(c.work, "pki")
	dirs := []string{pki, filepath.Join(c.work, "bootstrap")}
	var addrs []string
	for _, n := range dcMembers {
		pub, e1 := dcFreeAddress()
		peer, e2 := dcFreeAddress()
		if e1 != nil || e2 != nil {
			return nil, errors.Join(e1, e2)
		}
		c.public[n.id], c.peer[n.id], c.dial[n.id] = pub, peer, peer
		if opts.proxy {
			if c.link == nil {
				c.link = newDCNet()
			}
			if c.dial[n.id], err = c.link.listen(n.id, peer); err != nil {
				return nil, err
			}
		}
		c.data[n.id] = filepath.Join(c.work, "node-"+n.name)
		c.logs[n.id] = newDCLog("member-" + n.name)
		dirs = append(dirs, c.data[n.id])
		addrs = append(addrs, pub, peer, c.dial[n.id])
	}
	if err = env.Approve(dirs, addrs); err != nil {
		return nil, err
	}
	c.watchSignals()
	if err = os.MkdirAll(pki, 0o700); err != nil {
		return nil, err
	}
	ca, certs, keys, err := dcPKI(pki)
	if err != nil {
		return nil, err
	}
	c.seed = filepath.Join(c.work, "cluster.seed")
	var nodes []config.Node
	for _, n := range dcMembers {
		nodes = append(nodes, config.Node{ID: n.id, Identity: n.identity, FailureDomain: "process-directory-" + n.name, PeerAddress: config.Endpoint("https://" + c.dial[n.id]), PeerListen: c.peer[n.id],
			Disk: config.Disk{ID: "directory-" + n.name, Volume: "directory-" + n.name, Path: c.data[n.id], CapacityBytes: 1 << 30}, Certificate: certs[n.id], PrivateKey: config.NewSecretRef("file:" + keys[n.id])})
	}
	c.cfg = config.InstallConfig{
		Mode: config.ModeDistributed, ReplicationFactor: 3,
		Cluster:   config.Cluster{Placement: config.PlacementSimulated, CA: ca, Seed: config.NewSecretRef("file:" + c.seed), InitialLeader: 1, Revision: 1},
		Nodes:     nodes,
		Listen:    config.Listen{Address: "127.0.0.1:0", PublicOrigins: []string{"https://soundpost.example.invalid"}},
		Sources:   []config.SourcePolicy{{ID: "backend", Class: "private"}},
		Quotas:    config.Quotas{MaxBytesPerSource: 1 << 30, MaxSeriesPerSource: 1000},
		Retention: config.Retention{Days: map[string]uint32{"metric": 30, "log": 14}},
		Backup:    config.Backup{Mode: config.BackupNone},
	}
	if err = config.Validate(c.cfg); err != nil {
		return nil, err
	}
	return c, nil
}

func dcWaitCertificate(dataDir, addr string, done <-chan struct{}, limit time.Duration) (*x509.Certificate, error) {
	deadline := time.Now().Add(limit)
	for time.Now().Before(deadline) {
		select {
		case <-done:
			return nil, &dcFailure{Stage: "server_start", Code: "exited_before_listening"}
		default:
		}
		if raw, err := os.ReadFile(filepath.Join(dataDir, "server.crt")); err == nil {
			if block, _ := pem.Decode(raw); block != nil {
				if cert, err := x509.ParseCertificate(block.Bytes); err == nil {
					if conn, err := net.DialTimeout("tcp", addr, time.Second); err == nil {
						conn.Close()
						return cert, nil
					}
				}
			}
		}
		time.Sleep(25 * time.Millisecond)
	}
	return nil, &dcFailure{Stage: "server_start", Code: "timeout"}
}

// bootstrapAndStart bootstraps ONE installation, exports its seed, writes the generated node files
// and starts the three members.
func (c *dcCluster) bootstrapAndStart() error {
	dir := filepath.Join(c.work, "bootstrap")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	addr, err := dcFreeAddress()
	if err != nil {
		return err
	}
	if err = c.env.Approve([]string{dir}, []string{addr}); err != nil {
		return err
	}
	logs := &dcLog{}
	cmd := exec.Command(c.binary, "serve", "--mode=single", "--data-dir", dir, "--listen", addr)
	cmd.Stdout, cmd.Stderr = logs, logs
	cmd.Env = []string{"PATH=" + os.Getenv("PATH")}
	if err = cmd.Start(); err != nil {
		return err
	}
	done := make(chan struct{})
	go func() { _ = cmd.Wait(); close(done) }()
	c.mu.Lock()
	c.procs[0] = &dcProc{cmd: cmd, done: done} // the bootstrap process; killAll must reach it too
	c.mu.Unlock()
	stopped := false
	defer func() {
		if !stopped {
			_ = cmd.Process.Kill()
			<-done
		}
	}()
	cert, err := dcWaitCertificate(dir, addr, done, 30*time.Second)
	if err != nil {
		return err
	}
	site := newDCSite("https://"+addr, cert, 20*time.Second)
	if err = dcWaitSiteReady(site, 60*time.Second); err != nil {
		return err
	}
	var token []byte
	for deadline := time.Now().Add(30 * time.Second); time.Now().Before(deadline); time.Sleep(50 * time.Millisecond) {
		if token, err = os.ReadFile(filepath.Join(dir, "bootstrap.token")); err == nil {
			break
		}
	}
	if err != nil {
		return &dcFailure{Stage: "bootstrap_token", Code: "missing"}
	}
	if c.fx, err = dcBootstrap(site, string(token)); err != nil {
		return err
	}
	if err = cmd.Process.Signal(syscall.SIGTERM); err != nil {
		return err
	}
	select {
	case <-done:
		stopped = true
		c.mu.Lock()
		delete(c.procs, 0)
		c.mu.Unlock()
	case <-time.After(30 * time.Second):
		return &dcFailure{Stage: "bootstrap_stop", Code: "timeout"}
	}
	if out, err := exec.Command(c.binary, "cluster-seed", "--data-dir", dir, "--output", c.seed).CombinedOutput(); err != nil {
		_ = out
		return &dcFailure{Stage: "cluster_seed", Code: "command_failed"}
	}
	files, err := config.NodeConfigs(c.cfg)
	if err != nil {
		return err
	}
	for id, content := range files {
		if c.opts.proxy {
			// Each member dials its peers from its own loopback address 127.0.0.<id>; the drill's proxy
			// tells the dialers apart by it.
			var node map[string]any
			if err = json.Unmarshal(content, &node); err != nil {
				return err
			}
			node["peer_source_ip"] = fmt.Sprintf("127.0.0.%d", id)
			if content, err = json.MarshalIndent(node, "", "  "); err != nil {
				return err
			}
			content = append(content, '\n')
		}
		if err = os.WriteFile(filepath.Join(c.work, fmt.Sprintf("node-%d.json", id)), content, 0o600); err != nil {
			return err
		}
	}
	for _, n := range dcMembers {
		if err = c.start(n.id); err != nil {
			return err
		}
	}
	for _, n := range dcMembers {
		if err = c.waitReady(n.id, 180*time.Second); err != nil {
			return err
		}
	}
	return nil
}

func dcWaitSiteReady(site *dcSite, limit time.Duration) error {
	deadline := time.Now().Add(limit)
	for time.Now().Before(deadline) {
		if code, raw, err := site.get("/readyz"); err == nil && code == 200 {
			var st dcReady
			if json.Unmarshal(raw, &st) == nil && st.Ready {
				return nil
			}
		}
		time.Sleep(100 * time.Millisecond)
	}
	return &dcFailure{Stage: "bootstrap_ready", Code: "timeout"}
}

// start launches one member (a fresh process on its existing data directory).
func (c *dcCluster) start(id uint64) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.procs[id] != nil {
		return errors.New("member already running")
	}
	args := []string{"serve", "--mode=distributed", "--node-id", strconv.FormatUint(id, 10), "--cluster-config", filepath.Join(c.work, fmt.Sprintf("node-%d.json", id)), "--data-dir", c.data[id], "--listen", c.public[id]}
	c.logs[id].newIncarnation()
	var cmd *exec.Cmd
	if c.opts.inject {
		if err := os.MkdirAll(c.data[id], 0o700); err != nil {
			return err
		}
		disk := c.disks[id]
		if disk == nil {
			var err error
			if disk, err = newDCDisk(c.data[id], filepath.Join(c.work, fmt.Sprintf("shadow-%d", id))); err != nil {
				return err
			}
			c.disks[id] = disk
		}
		disk.stop()
		var err error
		if cmd, err = dcSpawnFaulted(disk, c.binary, args, c.logs[id]); err != nil {
			return err
		}
	} else {
		cmd = exec.Command(c.binary, args...)
		cmd.Stdout, cmd.Stderr = c.logs[id], c.logs[id]
		cmd.Env = []string{"PATH=" + os.Getenv("PATH")}
		dcOwnGroup(cmd)
		if err := cmd.Start(); err != nil {
			return err
		}
	}
	done := make(chan struct{})
	go func() { _ = cmd.Wait(); close(done) }()
	c.procs[id] = &dcProc{cmd: cmd, done: done}
	delete(c.sites, id)
	delete(c.sessions, id)
	delete(c.down, id)
	return nil
}

func (c *dcCluster) proc(id uint64) (*dcProc, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	p := c.procs[id]
	if p == nil {
		return nil, fmt.Errorf("member %d is not running", id)
	}
	return p, nil
}

// kill SIGKILLs one member, waits for its exit and returns the signal that ended it. The member is
// marked down BEFORE the signal so a reader of the live set never targets it after this returns.
func (c *dcCluster) kill(id uint64) (string, error) {
	p, err := c.proc(id)
	if err != nil {
		return "", err
	}
	if err = p.cmd.Process.Kill(); err != nil {
		return "", err
	}
	select {
	case <-p.done:
	case <-time.After(30 * time.Second):
		return "", &dcFailure{Stage: "kill", Code: "process_did_not_exit"}
	}
	c.mu.Lock()
	delete(c.procs, id)
	c.down[id] = true
	c.mu.Unlock()
	signal := "none"
	if ws, ok := p.cmd.ProcessState.Sys().(syscall.WaitStatus); ok && ws.Signaled() {
		signal = ws.Signal().String()
	}
	return signal, nil
}

// pause SIGSTOPs one member and proves from /proc that the process really is stopped.
func (c *dcCluster) pause(id uint64) error {
	p, err := c.proc(id)
	if err != nil {
		return err
	}
	if err = p.cmd.Process.Signal(dcSigStop); err != nil {
		return err
	}
	if err = c.waitState(p, func(s byte) bool { return s == 'T' }, 10*time.Second); err != nil {
		return err
	}
	c.mu.Lock()
	c.down[id] = true
	c.mu.Unlock()
	return nil
}

// resume SIGCONTs one member and proves from /proc that it is running again.
func (c *dcCluster) resume(id uint64) error {
	p, err := c.proc(id)
	if err != nil {
		return err
	}
	if err = p.cmd.Process.Signal(dcSigCont); err != nil {
		return err
	}
	if err = c.waitState(p, func(s byte) bool { return s != 'T' }, 10*time.Second); err != nil {
		return err
	}
	c.mu.Lock()
	delete(c.down, id)
	c.mu.Unlock()
	return nil
}

func (c *dcCluster) waitState(p *dcProc, ok func(byte) bool, limit time.Duration) error {
	deadline := time.Now().Add(limit)
	for time.Now().Before(deadline) {
		raw, err := os.ReadFile(fmt.Sprintf("/proc/%d/stat", p.cmd.Process.Pid))
		if err != nil {
			return &dcFailure{Stage: "process_state", Code: "proc_unreadable"}
		}
		state, err := dcProcState(string(raw))
		if err != nil {
			return err
		}
		if ok(state) {
			return nil
		}
		time.Sleep(20 * time.Millisecond)
	}
	return &dcFailure{Stage: "process_state", Code: "state_not_reached"}
}

// live is the sorted set of members known to answer (neither killed nor paused).
func (c *dcCluster) live() []uint64 {
	c.mu.Lock()
	defer c.mu.Unlock()
	var out []uint64
	for _, n := range dcMembers {
		if c.procs[n.id] != nil && !c.down[n.id] {
			out = append(out, n.id)
		}
	}
	return out
}

// close stops the signal watcher, resumes every member (a stopped process would otherwise stay in
// state T), kills every process this cluster started and waits for them.
func (c *dcCluster) close() {
	c.quitOnce.Do(func() { close(c.quit) })
	c.killAll()
	if c.link != nil {
		c.link.close()
	}
	for _, d := range c.disks {
		d.stop()
	}
}

func (c *dcCluster) killAll() {
	c.mu.Lock()
	procs := make(map[uint64]*dcProc, len(c.procs))
	for id, p := range c.procs {
		procs[id] = p
	}
	c.mu.Unlock()
	for _, p := range procs {
		_ = p.cmd.Process.Signal(dcSigCont)
		_ = p.cmd.Process.Kill()
	}
	for _, p := range procs {
		select {
		case <-p.done:
		case <-time.After(30 * time.Second):
		}
	}
}

// watchSignals makes an interrupted drill (Ctrl-C, SIGTERM) take its processes down with it
// instead of leaving stopped or orphaned members behind.
func (c *dcCluster) watchSignals() {
	sig := make(chan os.Signal, 1)
	signal.Notify(sig, os.Interrupt, syscall.SIGTERM)
	go func() {
		defer signal.Stop(sig)
		select {
		case <-sig:
			c.killAll()
			os.Exit(130)
		case <-c.quit:
		}
	}()
}

// site returns the HTTPS client of one member, pinned to the certificate the member generated.
func (c *dcCluster) site(id uint64) (*dcSite, error) {
	c.mu.Lock()
	s := c.sites[id]
	p := c.procs[id]
	c.mu.Unlock()
	if s != nil {
		return s, nil
	}
	if p == nil {
		return nil, fmt.Errorf("member %d is not running", id)
	}
	cert, err := dcWaitCertificate(c.data[id], c.public[id], p.done, 60*time.Second)
	if err != nil {
		return nil, err
	}
	s = newDCSite("https://"+c.public[id], cert, 20*time.Second)
	c.mu.Lock()
	c.sites[id] = s
	c.mu.Unlock()
	return s, nil
}

// dcReady is the /readyz answer: ready, a closed unready reason and the control applied cursor.
type dcReady struct {
	Ready   bool          `json:"ready"`
	Reason  string        `json:"reason"`
	Applied *model.Cursor `json:"applied_cursor"`
}

// readiness asks one member's /readyz with a short timeout (a stopped member never answers).
func (c *dcCluster) readiness(id uint64, timeout time.Duration) (int, dcReady, error) {
	var st dcReady
	s, err := c.site(id)
	if err != nil {
		return 0, st, err
	}
	code, raw, err := s.withTimeout(timeout).get("/readyz")
	if err != nil {
		return 0, st, err
	}
	if json.Unmarshal(raw, &st) != nil {
		return code, st, &dcFailure{Stage: "readyz", Code: "decode", Status: code}
	}
	st.Reason = dcSafeToken(st.Reason)
	if st.Ready {
		st.Reason = ""
	}
	return code, st, nil
}

// waitReady waits until the member answers /readyz 200 ready; a member that exited fails at once.
func (c *dcCluster) waitReady(id uint64, limit time.Duration) error {
	deadline := time.Now().Add(limit)
	last := "no_answer"
	for time.Now().Before(deadline) {
		if p, err := c.proc(id); err != nil {
			return err
		} else {
			select {
			case <-p.done:
				return &dcFailure{Stage: "member_ready", Code: "process_exited"}
			default:
			}
		}
		code, st, err := c.readiness(id, 3*time.Second)
		if err == nil && code == 200 && st.Ready {
			return nil
		}
		if err == nil {
			last = st.Reason
		}
		time.Sleep(200 * time.Millisecond)
	}
	return &dcFailure{Stage: "member_ready", Code: "timeout_" + dcSafeToken(last)}
}

// waitReadyOrRefused waits until the restarted member either becomes ready or exits on its own with exactly the
// closed reason refusal. It returns "ready" or "refused"; any other exit, or neither within limit, is an error.
func (c *dcCluster) waitReadyOrRefused(id uint64, refusal string, limit time.Duration) (string, string, error) {
	p, err := c.proc(id)
	if err != nil {
		return "", "", err
	}
	deadline := time.After(limit)
	for {
		select {
		case <-p.done:
			got := c.logs[id].lastReason()
			if got != refusal {
				return "", got, &dcFailure{Stage: "member_restart", Code: "exited_reason_" + dcSafeToken(got)}
			}
			return "refused", got, nil
		case <-deadline:
			return "", "", &dcFailure{Stage: "member_restart", Code: "neither_ready_nor_refused"}
		case <-time.After(200 * time.Millisecond):
			if code, st, rerr := c.readiness(id, 2*time.Second); rerr == nil && code == 200 && st.Ready {
				return "ready", "", nil
			}
		}
	}
}

// retire removes an exited member from the cluster bookkeeping for the rest of the drill: it is never written to,
// read from or waited for again (its replacement would be a new identity, which these drills do not add).
func (c *dcCluster) retire(id uint64) {
	c.mu.Lock()
	defer c.mu.Unlock()
	delete(c.procs, id)
	delete(c.sites, id)
	c.down[id] = true
	if c.retired == nil {
		c.retired = map[uint64]bool{}
	}
	c.retired[id] = true
}

// members is the set of members still in the drill (every member except retired ones).
func (c *dcCluster) members() []uint64 {
	c.mu.Lock()
	defer c.mu.Unlock()
	var out []uint64
	for _, n := range dcMembers {
		if !c.retired[n.id] {
			out = append(out, n.id)
		}
	}
	return out
}

// converged waits until every member is ready and reports the same control applied index, and
// returns the cursors.
func (c *dcCluster) converged(limit time.Duration) (map[uint64]uint64, error) {
	deadline := time.Now().Add(limit)
	ids := c.members()
	for time.Now().Before(deadline) {
		seen := map[uint64]uint64{}
		for _, id := range ids {
			code, st, err := c.readiness(id, 3*time.Second)
			if err != nil || code != 200 || !st.Ready || st.Applied == nil {
				break
			}
			seen[id] = uint64(st.Applied.Index)
		}
		if dcSameCursor(seen, len(ids)) {
			return seen, nil
		}
		time.Sleep(300 * time.Millisecond)
	}
	return nil, &dcFailure{Stage: "converge", Code: "applied_cursors_differ"}
}


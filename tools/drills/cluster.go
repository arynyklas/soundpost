var dcFeatureSet = regexp.MustCompile(`"feature_sets"\s*:\s*\[\s*\{\s*"id"\s*:\s*"([^"]+)"`)

// login opens a fresh reader session on one member.
func (c *dcCluster) login(id uint64) (auth.Session, error) {
	var session auth.Session
	s, err := c.site(id)
	if err != nil {
		return session, err
	}
	status, raw, err := s.post("/api/v1/login", map[string]string{"Email": c.fx.readerEmail, "Password": dcReaderPassword, "Code": ""}, "", "")
	if err = dcRequire("reader_login", status, 200, err); err != nil {
		return session, err
	}
	if err = json.Unmarshal(raw, &session); err != nil {
		return session, err
	}
	c.mu.Lock()
	c.sessions[id] = session
	c.mu.Unlock()
	return session, nil
}

// queryRaw runs one PromQL instant query on one member as the project reader and returns the
// status, the body and the transport error exactly as the member answered.
func (c *dcCluster) queryRaw(id uint64, expression string, timeout time.Duration) (int, []byte, error) {
	s, err := c.site(id)
	if err != nil {
		return 0, nil, err
	}
	c.mu.Lock()
	session, ok := c.sessions[id]
	c.mu.Unlock()
	if !ok {
		if session, err = c.login(id); err != nil {
			return 0, nil, err
		}
	}
	const profile = "promql-prometheus-3.1.0"
	files, err := profiles.Query()
	if err != nil {
		return 0, nil, err
	}
	manifest, err := fs.ReadFile(files, profile+".json")
	if err != nil {
		return 0, nil, err
	}
	match := dcFeatureSet.FindSubmatch(manifest)
	if match == nil {
		return 0, nil, &dcFailure{Stage: "query", Code: "feature_set"}
	}
	body := map[string]any{"org": c.fx.org.String(), "language": "promql", "profile": profile, "feature_set": string(match[1]), "expression": expression,
		"evaluation": map[string]any{"instant": true, "time": fmt.Sprint(time.Now().Add(time.Minute).UnixNano()), "start": "0", "end": "0", "step": "0"},
		"projects":   []string{c.fx.project.String()}, "budget": map[string]any{"timeout_ns": "0", "memory_bytes": "0", "max_returned": "0"}, "allow_partial": false}
	return s.withTimeout(timeout).post("/api/v1/query", body, session.CSRF, "")
}

// readBack reads every drill series of one member: batch id -> digest of the data read back and
// batch id -> number of stored samples. Any non-complete answer is an error (the caller retries).
func (c *dcCluster) readBack(id uint64) (map[string]string, map[string]uint64, error) {
	if _, err := c.login(id); err != nil {
		return nil, nil, err
	}
	status, raw, err := c.queryRaw(id, "last_over_time("+dcMetric+"[30m])", 30*time.Second)
	if err != nil {
		return nil, nil, &dcFailure{Stage: "read_back", Code: dcTransportClass(err)}
	}
	if status != 200 {
		return nil, nil, &dcFailure{Stage: "read_back", Code: "unexpected_status", Status: status}
	}
	digests, err := dcVectorDigests(raw)
	if err != nil {
		return nil, nil, &dcFailure{Stage: "read_back", Code: err.Error()}
	}
	status, raw, err = c.queryRaw(id, "count_over_time("+dcMetric+"[30m])", 30*time.Second)
	if err != nil {
		return nil, nil, &dcFailure{Stage: "read_back_counts", Code: dcTransportClass(err)}
	}
	if status != 200 {
		return nil, nil, &dcFailure{Stage: "read_back_counts", Code: "unexpected_status", Status: status}
	}
	counts, err := dcSampleCounts(raw)
	if err != nil {
		return nil, nil, &dcFailure{Stage: "read_back_counts", Code: err.Error()}
	}
	return digests, counts, nil
}

// retains polls one member until it retains every acknowledged id with its exact digest (a member
// that was down legitimately needs time to catch up) or the limit passes. It returns the last
// data read back so the caller can reconcile it and report the exact difference.
func (c *dcCluster) retains(id uint64, led *Ledger, limit time.Duration) (map[string]string, map[string]uint64, error) {
	deadline := time.Now().Add(limit)
	var digests map[string]string
	var counts map[string]uint64
	var lastErr error
	for tries := 0; ; tries++ {
		if tries > 0 && tries%10 == 0 {
			c.env.Logf("member %d still does not retain every acknowledged id: %v", id, lastErr)
		}
		d, n, err := c.readBack(id)
		if err == nil {
			digests, counts, lastErr = d, n, nil
			if _, rerr := Reconcile(led, d); rerr == nil {
				return digests, counts, nil
			} else {
				lastErr = rerr
			}
		} else {
			lastErr = err
		}
		if time.Now().After(deadline) {
			return digests, counts, lastErr
		}
		time.Sleep(500 * time.Millisecond)
	}
}

// ---- writer ----

// dcWriter issues drill batches, delivers them with retry of the SAME batch, and records every
// acknowledgement in the ledger and every non-acknowledged attempt as a failed attempt.
type dcWriter struct {
	c   *dcCluster
	led *Ledger
	max int

	mu       sync.Mutex
	seq      int
	batches  map[string]model.Batch
	bodies   map[string][]byte
	receipts map[string]model.Receipt
	sent     []dcSent
	times    []dcAckTime
	issued   map[string]bool

	stop     chan struct{}
	failed   chan struct{}
	failOnce sync.Once
	wg       sync.WaitGroup
	abort    chan struct{}
	err      error

	claimed atomic.Int64 // batches the running stream has issued
	allowed atomic.Int64 // batches the running stream may issue
}

func newDCWriter(c *dcCluster, led *Ledger, max int) *dcWriter {
	return &dcWriter{c: c, led: led, max: max, batches: map[string]model.Batch{}, bodies: map[string][]byte{}, receipts: map[string]model.Receipt{}, issued: map[string]bool{}, abort: make(chan struct{})}
}

// next builds the next batch: one metric record, a unique batch id, a unique float value.
func (w *dcWriter) next() (model.Batch, error) {
	w.mu.Lock()
	w.seq++
	seq := w.seq
	w.mu.Unlock()
	if seq > w.max || seq > len(w.c.fx.pool) {
		return model.Batch{}, fmt.Errorf("drill series budget of %d batches exhausted", min(w.max, len(w.c.fx.pool)))
	}
	fx := w.c.fx
	id := fx.pool[seq-1]
	value := model.FloatBits(math.Float64bits(float64(seq) + 0.25))
	resource := model.Resource{Service: fx.service, Environment: fx.environment, Build: fx.build, Instance: "instance", Labels: model.Labels{}}
	record := model.Record{ID: model.NewID(), Kind: model.Metric, ObservedAt: model.UnixNano(time.Now().UnixNano()), Resource: resource,
		Payload: model.Payload{Metric: &model.MetricPoint{Name: dcMetric, Labels: model.Labels{{Name: "batch", Value: id.String()}}, SampleKind: "float", Value: &value, Unit: "1", Type: "gauge"}}}
	batch := model.Batch{Version: 1, Project: fx.project, Source: fx.source, Producer: model.NewID(), ID: id, PolicyRevision: 1, Records: []model.Record{record}}
	slot, err := model.OwnerSlot(fx.org, fx.project, fx.source, batch.Producer, record)
	if err != nil {
		return batch, err
	}
	batch.RouteSlot = slot
	body, err := json.Marshal(batch)
	if err != nil {
		return batch, err
	}
	w.mu.Lock()
	w.batches[id.String()], w.bodies[id.String()] = batch, body
	w.issued[id.String()] = true
	w.mu.Unlock()
	return batch, nil
}

// Issued is the set of batch ids this writer ever created.
func (w *dcWriter) Issued() map[string]bool {
	w.mu.Lock()
	defer w.mu.Unlock()
	out := make(map[string]bool, len(w.issued))
	for k := range w.issued {
		out[k] = true
	}
	return out
}

// attempt sends one batch to one member ONCE. A success is recorded as an ACK (with the exact
// semantic digest of the batch); anything else is recorded as a failed attempt. A repeated
// acknowledgement must carry the same receipt as the first.
func (w *dcWriter) attempt(member uint64, b model.Batch, timeout time.Duration, label string) (dcVerdict, string, error) {
	id := b.ID.String()
	_, digest, err := dcBatchSemantics(b)
	if err != nil {
		return dcMalformed, "", err
	}
	w.mu.Lock()
	body := w.bodies[id]
	w.mu.Unlock()
	started := time.Now()
	site, err := w.c.site(member)
	var status int
	var raw []byte
	if err == nil {
		status, raw, err = site.withTimeout(timeout).postRaw("/ingest/v1/batches", body, "", w.c.fx.credential)
	}
	sum := sha256.Sum256(body)
	verdict, detail, receipt := dcClassifyIngest(status, raw, err, b.ID)
	w.mu.Lock()
	w.sent = append(w.sent, dcSent{ID: id, Member: member, BodyHash: hex.EncodeToString(sum[:8]), Verdict: verdict})
	w.mu.Unlock()
	if verdict != dcAcked {
		w.led.Attempted(Attempt{ID: id, Outcome: string(verdict), Detail: "member_" + strconv.FormatUint(member, 10) + "_" + detail})
		return verdict, detail, nil
	}
	w.mu.Lock()
	first, seen := w.receipts[id]
	if !seen {
		w.receipts[id] = receipt
	}
	w.mu.Unlock()
	if seen && (first.Hash != receipt.Hash || first.Cursor != receipt.Cursor) {
		return dcMalformed, "retry_changed_the_receipt", &dcFailure{Stage: "retry_receipt", Code: "receipt_differs_from_first_acknowledgement"}
	}
	if err = w.led.Record(Ack{ID: id, Group: receipt.Cursor.Group.String(), Index: uint64(receipt.Cursor.Index), Digest: digest, Label: label}); err != nil {
		return dcMalformed, "ledger", err
	}
	w.mu.Lock()
	w.times = append(w.times, dcAckTime{ID: id, Member: member, Started: started, At: time.Now()})
	w.mu.Unlock()
	return dcAcked, detail, nil
}

// deliver retries the SAME batch across the given members until one acknowledges it. Only typed
// refusals and transport failures are retried; any other answer ends the drill.
func (w *dcWriter) deliver(b model.Batch, members func() []uint64, limit time.Duration, label string) (uint64, error) {
	deadline := time.Now().Add(limit)
	for {
		for _, m := range members() {
			select {
			case <-w.abort:
				return 0, errors.New("delivery aborted: the drill is unwinding")
			default:
			}
			verdict, detail, err := w.attempt(m, b, 8*time.Second, label)
			if err != nil {
				return 0, err
			}
			switch verdict {
			case dcAcked:
				return m, nil
			case dcTypedRefusal, dcTransport:
			default:
				return 0, &dcFailure{Stage: "deliver", Code: string(verdict) + "_" + detail}
			}
		}
		if time.Now().After(deadline) {
			return 0, &dcFailure{Stage: "deliver", Code: "not_acknowledged_within_limit"}
		}
		time.Sleep(300 * time.Millisecond)
	}
}

// rotate returns the live members starting at a rotating position.
func (w *dcWriter) rotate(i int) func() []uint64 {
	return func() []uint64 {
		live := w.c.live()
		if len(live) == 0 {
			return nil
		}
		out := make([]uint64, 0, len(live))
		for k := range live {
			out = append(out, live[(i+k)%len(live)])
		}
		return out
	}
}

// startStream runs `workers` concurrent writers. Each writes one new batch after another (pace
// apart), through a rotating live member, retrying the SAME batch until it is acknowledged. Several
// concurrent writers make it likely that a fault lands while a request is in flight. At most
// `budget` batches are issued in this stream (the series pool is finite) unless grantBudget adds
// to it; a worker past the budget idles until the stream is stopped or the budget grows.
func (w *dcWriter) startStream(workers int, pace time.Duration, budget int, label string) {
	w.stop, w.failed, w.err, w.failOnce = make(chan struct{}), make(chan struct{}), nil, sync.Once{}
	w.claimed.Store(0)
	w.allowed.Store(int64(budget))
	for k := range workers {
		w.wg.Add(1)
		go func() {
			defer w.wg.Done()
			for i := k; ; i += workers {
				select {
				case <-w.stop:
					return
				default:
				}
				if w.claim() {
					b, err := w.next()
					if err == nil {
						_, err = w.deliver(b, w.rotate(i), 150*time.Second, label)
					}
					if err != nil {
						w.failOnce.Do(func() { w.err = err; close(w.failed) })
						return
					}
				}
				select {
				case <-w.stop:
					return
				case <-time.After(pace):
				}
			}
		}()
	}
}

// claim takes one batch of the running stream's budget; false once the budget is spent.
func (w *dcWriter) claim() bool {
	for {
		n := w.claimed.Load()
		if n >= w.allowed.Load() {
			return false
		}
		if w.claimed.CompareAndSwap(n, n+1) {
			return true
		}
	}
}

// grantBudget lets the idle workers of the running stream issue n more batches. A restored member
// can take longer than the stream's budget lasts to become ready (it was 11 s for a 100 batch
// budget); the acknowledgements the drill requires AFTER the restore still have to come from a
// stream that is running, never from a stream that went idle while the member was starting.
func (w *dcWriter) grantBudget(n int) { w.allowed.Add(int64(n)) }

// stopStream stops the stream after every batch in flight is acknowledged and returns its error.
func (w *dcWriter) stopStream() error {
	close(w.stop)
	w.wg.Wait()
	return w.err
}

// abortStream is the error-path stop: the batches in flight are abandoned (each stays a failed
// attempt in the ledger) so a drill that is already failing never waits for a dead cluster.
func (w *dcWriter) abortStream() {
	close(w.abort)
	close(w.stop)
	w.wg.Wait()
}

// streamFailed reports a stream worker that ended with an error.
func (w *dcWriter) streamFailed() error {
	select {
	case <-w.failed:
		return w.err
	default:
		return nil
	}
}

// Times returns a copy of the acknowledgement times.
func (w *dcWriter) Times() []dcAckTime {
	w.mu.Lock()
	defer w.mu.Unlock()
	return append([]dcAckTime(nil), w.times...)
}

// Sent returns a copy of every attempt made.
func (w *dcWriter) Sent() []dcSent {
	w.mu.Lock()
	defer w.mu.Unlock()
	return append([]dcSent(nil), w.sent...)
}

// waitAcks waits until n acknowledged requests were STARTED after `from` (a zero `from` counts all).
func (w *dcWriter) waitAcks(n int, from time.Time, limit time.Duration) error {
	deadline := time.Now().Add(limit)
	for time.Now().Before(deadline) {
		if err := w.streamFailed(); err != nil {
			return err
		}
		if dcAcksStartedAfter(w.Times(), from) >= n {
			return nil
		}
		time.Sleep(100 * time.Millisecond)
	}
	return &dcFailure{Stage: "wait_acks", Code: "timeout"}
}

// resend posts an already acknowledged batch again to one member and returns the verdict; the
// receipt consistency is enforced by attempt (same hash and cursor as the first acknowledgement).
// A typed retryable answer (503: the member is catching up) is what a client retries with the identical
// body, so it is retried for up to 60 s; anything else is returned as is, and a retry that never
// acknowledges still fails the check.
func (w *dcWriter) resend(member uint64, id string) (dcVerdict, error) {
	w.mu.Lock()
	b, ok := w.batches[id]
	w.mu.Unlock()
	if !ok {
		return dcMalformed, errors.New("unknown batch")
	}
	deadline := time.Now().Add(60 * time.Second)
	for {
		v, _, err := w.attempt(member, b, 20*time.Second, "resend")
		if err != nil || v != dcTypedRefusal || time.Now().After(deadline) {
			return v, err
		}
		time.Sleep(500 * time.Millisecond)
	}
}

// lookupReceipt asks one member for the receipt of an acknowledged batch and compares it with the
// original acknowledgement.
func (w *dcWriter) lookupReceipt(member uint64, id string) error {
	w.mu.Lock()
	b, ok := w.batches[id]
	original, has := w.receipts[id]
	w.mu.Unlock()
	if !ok || !has {
		return errors.New("batch was never acknowledged")
	}
	site, err := w.c.site(member)
	if err != nil {
		return err
	}
	status, raw, err := site.withTimeout(20*time.Second).post("/ingest/v1/receipts", model.ReceiptRequest{Source: b.Source, Producer: b.Producer, RouteSlot: b.RouteSlot, BatchID: original.BatchID, OriginalHash: original.Hash}, "", w.c.fx.credential)
	if err = dcRequire("receipt_lookup", status, 200, err); err != nil {
		return err
	}
	var got model.Receipt
	if json.Unmarshal(raw, &got) != nil || got.BatchID != original.BatchID || got.Hash != original.Hash || got.Cursor != original.Cursor {
		return &dcFailure{Stage: "receipt_lookup", Code: "receipt_differs_from_first_acknowledgement"}
	}
	return nil
}

// ---- shared per-member verification ----

// dcReadFunc reads back one member: digests per batch id, stored sample count per batch id.
type dcReadFunc func(member uint64) (map[string]string, map[string]uint64, error)

// dcVerifyMembers reads back EVERY member of the cluster (waiting for each to retain every
// acknowledged id) and verifies them with dcVerifyWith.
func dcVerifyMembers(c *dcCluster, w *dcWriter, rep *Report, phase string, limit time.Duration) (map[string]string, error) {
	read := func(member uint64) (map[string]string, map[string]uint64, error) {
		began := time.Now()
		digests, counts, err := c.retains(member, rep.Ledger(), limit)
		c.env.Logf("%s: member %d read back in %dms", phase, member, time.Since(began).Milliseconds())
		return digests, counts, err
	}
	return dcVerifyWith(read, w.Issued(), rep, phase, c.members()...)
}

// dcVerifyWith records, for every member, exact reconciliation of the ledger against the data read
// back, single-copy storage and absence of ids this drill never issued, and then requires identical
// content across members. It returns the retained digests (one map for all members when they agree)
// and the first failure.
// members is the set to verify; empty means every member (a retired member is never read back).
func dcVerifyWith(read dcReadFunc, issued map[string]bool, rep *Report, phase string, members ...uint64) (map[string]string, error) {
	if len(members) == 0 {
		for _, n := range dcMembers {
			members = append(members, n.id)
		}
	}
	retained := map[uint64]map[string]string{}
	var first error
	keep := func(err error) {
		if first == nil {
			first = err
		}
	}
	for _, id := range members {
		digests, counts, err := read(id)
		name := fmt.Sprintf("%s_member_%d", phase, id)
		if digests == nil {
			keep(rep.Require(name+"_readable", false, fmt.Sprint(err)))
			continue
		}
		retained[id] = digests
		_, rerr := Reconcile(rep.Ledger(), digests)
		detail := fmt.Sprintf("%d acknowledged ids retained with identical semantic data", rep.Ledger().Len())
		if rerr != nil {
			detail = rerr.Error()
		}
		keep(rep.Require(name+"_exact_reconciliation", rerr == nil, detail))
		cerr := dcVerifyCounts(counts, rep.Ledger().Acks())
		detail = "every acknowledged id stored exactly once"
		if cerr != nil {
			detail = cerr.Error()
		}
		keep(rep.Require(name+"_no_duplicate_data", cerr == nil, detail))
		unknown := dcUnknownRetained(digests, issued)
		keep(rep.Require(name+"_no_unknown_ids", len(unknown) == 0, fmt.Sprintf("%d retained ids were never issued by this drill", len(unknown))))
	}
	if first != nil {
		return nil, first
	}
	ierr := dcIdenticalMembers(retained)
	detail := fmt.Sprintf("all %d members retain the same %d ids with identical content", len(retained), len(retained[members[0]]))
	if ierr != nil {
		detail = ierr.Error()
	}
	if err := rep.Require(phase+"_members_identical", ierr == nil, detail); err != nil {
		return nil, err
	}
	return retained[members[0]], nil
}

// dcRecordCursors converges the cluster and records the control applied index of every member.
func dcRecordCursors(c *dcCluster, rep *Report, phase string) error {
	cursors, err := c.converged(120 * time.Second)
	if err != nil {
		return rep.Require(phase+"_applied_cursors_converge", false, err.Error())
	}
	for id, v := range cursors {
		rep.Cursor(fmt.Sprintf("%s/control_applied_index/member_%d", phase, id), v)
	}
	return rep.Require(phase+"_applied_cursors_converge", true, fmt.Sprintf("all %d members report the same control applied index", len(cursors)))
}

// dcFaultSpec describes one fault of a stream-driven phase.
type dcFaultSpec struct {
	Phase   string // report key prefix
	Kind    string // "sigkill" or "sigstop"
	Victim  uint64
	Inject  func() error // takes the victim down
	Restore func() error // brings the victim back (start or SIGCONT); the member must then become ready
	During  func() error // optional: runs while the fault is active, after the survivors acknowledged, before Restore
	// MayRefuseAs, when set, is the one closed reason with which the restored member may refuse to rejoin instead of
	// becoming ready: a voter whose journal is behind what its identity acknowledged must refuse
	// (docs/operations/distributed.md), and whether it is behind can depend on what an intervening incarnation
	// acknowledged, which the drill cannot see. Exactly one of the two outcomes must happen: ready (then every
	// restored-member check below applies) or that exit (then the survivors must keep acknowledging, the member is
	// left out for the rest of the drill and verification covers the survivors). Any other exit fails.
	MayRefuseAs string
}

// dcRunStreamFault is one fault phase while writes stream: write, inject the fault mid-stream, make
// a probe write to the victim (it must not acknowledge) and retry that same batch through the
// survivors, keep acknowledging through the survivors, restore the victim, wait for /readyz, keep
// writing through all three members, then verify every member.
func dcRunStreamFault(c *dcCluster, w *dcWriter, rep *Report, spec dcFaultSpec) error {
	p := spec.Phase
	subject := fmt.Sprintf("member_%d", spec.Victim)
	w.startStream(4, 80*time.Millisecond, 100, p)
	stopped := false
	defer func() {
		if !stopped {
			w.abortStream()
		}
	}()
	if err := w.waitAcks(6, time.Time{}, 120*time.Second); err != nil {
		return rep.Require(p+"_stream_acks_before_fault", false, err.Error())
	}
	before := len(w.Times())
	if err := spec.Inject(); err != nil {
		return rep.Require(p+"_fault_injected", false, err.Error())
	}
	faulted := time.Now()
	c.env.Logf("%s: %s injected on member %d", p, spec.Kind, spec.Victim)
	rep.Fact(p+"/victim_member", spec.Victim)
	rep.Fact(p+"/fault", spec.Kind)
	rep.Fact(p+"/acks_before_fault", before)
	rep.Timeline().Fail(subject, spec.Kind+" injected while the write stream was running")

	// A write sent to the victim while it is down must not be acknowledged; the same batch is then
	// retried unchanged through the survivors.
	probe, err := w.next()
	if err != nil {
		return err
	}
	verdict, detail, err := w.attempt(spec.Victim, probe, 3*time.Second, p+"_probe")
	if err != nil {
		return err
	}
	if err = rep.Require(p+"_victim_does_not_acknowledge", verdict != dcAcked, "probe write to the down member: "+string(verdict)+" "+detail); err != nil {
		return err
	}
	rep.Timeline().Fail(subject, "probe write to the down member was not acknowledged: "+detail)
	via, err := w.deliver(probe, c.live, 120*time.Second, p+"_probe")
	if err != nil {
		return rep.Require(p+"_refused_write_retried_unchanged_to_ack", false, err.Error()+"; cluster at the failure: "+c.diagnose())
	}
	rep.Fact(p+"/probe_acknowledged_by_member", via)
	c.env.Logf("%s: probe batch acknowledged by member %d", p, via)
	rep.Timeline().Deliver("ingest", fmt.Sprintf("the refused probe batch was retried unchanged and acknowledged by member %d", via))

	if err = w.waitAcks(8, faulted, 120*time.Second); err != nil {
		return rep.Require(p+"_acks_through_survivors_while_victim_down", false, err.Error()+"; cluster at the failure: "+c.diagnose())
	}
	latency, ok := dcFirstAckAfter(w.Times(), faulted)
	if err = rep.Require(p+"_first_ack_after_fault", ok, "an acknowledgement of a request started after the fault completed"); err != nil {
		return err
	}
	rep.Fact(p+"/first_ack_after_fault_ms", latency.Milliseconds())

	if spec.During != nil {
		if err = spec.During(); err != nil {
			return rep.Require(p+"_checks_while_faulted", false, err.Error())
		}
	}
	c.env.Logf("%s: first ack after the fault %dms; restoring member %d", p, latency.Milliseconds(), spec.Victim)
	restoreAt := time.Now()
	if err = spec.Restore(); err != nil {
		return rep.Require(p+"_victim_restored", false, err.Error())
	}
	outcome := "ready"
	if spec.MayRefuseAs != "" {
		got := ""
		var rerr error
		outcome, got, rerr = c.waitReadyOrRefused(spec.Victim, spec.MayRefuseAs, 180*time.Second)
		rep.Fact(p+"/restart_outcome", outcome)
		if err = rep.Require(p+"_victim_ready_or_refuses_typed", rerr == nil, fmt.Sprintf("member %d: outcome %q, exit reason %q (allowed: ready, or refused with %s); err=%v", spec.Victim, outcome, got, spec.MayRefuseAs, rerr)); err != nil {
			return err
		}
	}
	if outcome == "refused" {
		// The member refused to rejoin with exactly the allowed closed reason and never became ready; the survivors
		// must keep acknowledging. It stays out of the drill (a replacement is a new identity, not this disk).
		refusedAt := time.Now()
		c.retire(spec.Victim)
		rep.Fact(p+"/victim_retired", spec.Victim)
		rep.Fact(p+"/refused_after_restore_ms", refusedAt.Sub(restoreAt).Milliseconds())
		w.grantBudget(30)
		if err = w.waitAcks(6, refusedAt, 120*time.Second); err != nil {
			return rep.Require(p+"_acks_through_survivors_after_refusal", false, err.Error()+"; cluster at the failure: "+c.diagnose())
		}
		stopped = true
		if err = w.stopStream(); err != nil {
			return rep.Require(p+"_stream_ended_cleanly", false, err.Error())
		}
		rep.Timeline().Deliver("ingest", fmt.Sprintf("the survivors kept acknowledging after member %d refused to rejoin", spec.Victim))
		// The service outage is over (deliveries after the last failure); member spec.Victim is not: it is retired.
		if err = rep.Timeline().Recover("cluster"); err != nil {
			return rep.Require(p+"_outage_recovered", false, err.Error())
		}
	} else {
		if err = c.waitReady(spec.Victim, 180*time.Second); err != nil {
			return rep.Require(p+"_victim_ready_after_restore", false, err.Error())
		}
		readyAt := time.Now()
		w.grantBudget(30) // the stream may have spent its budget while the member started; see grantBudget
		c.env.Logf("%s: member %d ready %dms after restore", p, spec.Victim, readyAt.Sub(restoreAt).Milliseconds())
		rep.Fact(p+"/ready_after_restore_ms", readyAt.Sub(restoreAt).Milliseconds())
		rep.Fact(p+"/acks_between_fault_and_ready", dcAcksBetween(w.Times(), faulted, readyAt))
		if err = w.waitAcks(6, readyAt, 120*time.Second); err != nil {
			return rep.Require(p+"_acks_after_restore", false, err.Error())
		}
		c.env.Logf("%s: 6 acks after the member was ready; stopping the stream", p)
		stopped = true
		if err = w.stopStream(); err != nil {
			return rep.Require(p+"_stream_ended_cleanly", false, err.Error())
		}
		// The restored member must itself acknowledge a fresh write again.
		last, err := w.next()
		if err != nil {
			return err
		}
		by, err := w.deliver(last, func() []uint64 { return []uint64{spec.Victim} }, 90*time.Second, p+"_restored")
		if err = rep.Require(p+"_restored_member_acknowledges", err == nil && by == spec.Victim, fmt.Sprintf("a fresh write sent only to member %d was acknowledged by it", spec.Victim)); err != nil {
			return err
		}
		rep.Timeline().Deliver(subject, "the restored member acknowledged a fresh write")
		if err = rep.Timeline().Recover(subject); err != nil {
			return rep.Require(p+"_outage_recovered", false, err.Error())
		}
	}

	c.env.Logf("%s: converging control cursors", p)
	if err = dcRecordCursors(c, rep, p); err != nil {
		return err
	}
	c.env.Logf("%s: retrying acknowledged batches on every member", p)
	if err = dcCheckRetries(c, w, rep, p, fmt.Sprintf("including the restored member %d", spec.Victim), probe.ID.String()); err != nil {
		return err
	}
	c.env.Logf("%s: verifying every member", p)
	if _, err = dcVerifyMembers(c, w, rep, p, 120*time.Second); err != nil {
		return err
	}
	rerr := dcVerifyRetries(w.Sent(), rep.Ledger().Acks())
	detail = fmt.Sprintf("%d attempts, %d failed attempts, every refused batch was retried with an identical body to an acknowledgement", len(w.Sent()), len(rep.Ledger().Attempts()))
	if rerr != nil {
		detail = rerr.Error()
	}
	return rep.Require(p+"_refused_attempts_retried_unchanged", rerr == nil, detail)
}

// dcCheckRetries re-posts three already acknowledged batches (the first of the drill, the probe
// that was refused and re-sent during the outage, the newest) to every member and requires the
// SAME receipt each time; the receipt lookup must agree.
func dcCheckRetries(c *dcCluster, w *dcWriter, rep *Report, phase, note, probeID string) error {
	acks := rep.Ledger().Acks()
	ids := []string{acks[0].ID, probeID, acks[len(acks)-1].ID}
	same := 0
	for _, id := range ids {
		for _, member := range c.members() {
			v, err := w.resend(member, id)
			if err != nil {
				return rep.Require(phase+"_retry_returns_same_receipt", false, err.Error())
			}
			if v != dcAcked {
				return rep.Require(phase+"_retry_returns_same_receipt", false, fmt.Sprintf("retry of an acknowledged batch on member %d answered %s", member, v))
			}
			if err = w.lookupReceipt(member, id); err != nil {
				return rep.Require(phase+"_retry_returns_same_receipt", false, err.Error())
			}
			same++
		}
	}
	return rep.Require(phase+"_retry_returns_same_receipt", true, fmt.Sprintf("%d retries of acknowledged batches (%s) returned the original receipt", same, note))
}

package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"github.com/arynyklas/soundpost/internal/sourcemap"
	"os"
	"path/filepath"
	"strings"
)

func runSourceMap(args []string) error {
	flags := flag.NewFlagSet("source-map", flag.ContinueOnError)
	dir := flags.String("artifact-dir", "", "directory generated by fixtures/artifacts/generate.mjs")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if *dir == "" {
		return fmt.Errorf("artifact-dir is required")
	}
	for _, entry := range []string{"simple", "indexed"} {
		b, e := os.ReadFile(filepath.Join(*dir, entry+".position.json"))
		if e != nil {
			return e
		}
		var want struct {
			GeneratedLine   uint32
			GeneratedColumn uint32
			SourceID        string
			Line            uint32
			Column          uint32
		}
		if e = json.Unmarshal(b, &want); e != nil {
			return e
		}
		f, e := os.Open(filepath.Join(*dir, entry+".mjs.map"))
		if e != nil {
			return e
		}
		m, e := sourcemap.Decode(f, sourcemap.Limits{})
		f.Close()
		if e != nil {
			return e
		}
		p, ok, e := m.Lookup(want.GeneratedLine, want.GeneratedColumn)
		if e != nil || !ok || p.SourceID != want.SourceID || p.Line != want.Line || p.Column != want.Column {
			return fmt.Errorf("real throwing fixture position mismatch")
		}
		if entry == "indexed" {
			f, e = os.Open(filepath.Join(*dir, "sections.map"))
			if e != nil {
				return e
			}
			m, e = sourcemap.Decode(f, sourcemap.Limits{})
			f.Close()
			if e != nil {
				return e
			}
			col := want.GeneratedColumn
			if want.GeneratedLine == 1 {
				col += 7
			}
			p, ok, e = m.Lookup(want.GeneratedLine+2, col)
			if e != nil || !ok || p.SourceID != want.SourceID || p.Line != want.Line || p.Column != want.Column {
				return fmt.Errorf("indexed fixture offset mismatch")
			}
		}
	}
	for _, bad := range []string{`{"version":3,"sections":[{"offset":{"line":0,"column":0},"url":"https://PRIVATE_CANARY.invalid"}]}`, `{"version":3,"sources":["../PRIVATE_CANARY"],"mappings":"AAAA"}`, `{"version":3,"sources":[],"mappings":"gggggggggggggA"}`} {
		_, e := sourcemap.Decode(strings.NewReader(bad), sourcemap.Limits{})
		if e == nil || strings.Contains(e.Error(), "PRIVATE_CANARY") {
			return fmt.Errorf("unsafe malformed-map handling")
		}
	}
	fmt.Println("source-map: actual thrown Vite positions and indexed offsets resolved; malformed maps rejected without content leakage")
	return nil
}

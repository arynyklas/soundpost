type dcRun struct {
	*dcRecorder
	wait, hold time.Duration
	lag        uint64   // the voter that is killed (or stopped for the backup) before the deletion
	live       []uint64 // the other two, in node order
	members    []uint64 // the voters of the cluster now (the lagging voter's replacement joins in replace mode)
	watch      uint64   // the voter whose directory must hold no canary whenever a receipt reads clean
	replace    bool     // replace the lagging voter by a fresh identity instead of restarting it

	// the restore authority and the older backup taken through it (setupAuthority, backupWhileDown)
	withAuthority  bool
	auth           *dcAuthority
	backup         dcBackupInfo // the older backup, taken before the deletion
	backupSibling  float64      // the sibling's latest value when that backup was taken
	authHead       backup.AuthorityHead
	authTombstones int
	fresh          dcFreshWatch // scans of the replacement's directory (replace mode)
	early          bool         // replace-early: the fresh identity joins as a learner before the deletion, holding the canary
	track          *dcCleanTrack

	cluster   *processCluster
	fx        *installFixture
	sites     map[uint64]*installSite // reader-side client per node (its own cookie jar)
	ownerSite map[uint64]*installSite // organization-owner client per node (its own cookie jar)
	owner     map[uint64]auth.Session
	reader    map[uint64]auth.Session
	canary    string
	op        model.ID
	sib       dcSibling
}

// login opens an owner session and a reader session on one node. They use separate clients:
// both sessions ride the same cookie name, so one jar would hold only the later login.
func (r *dcRun) login(id uint64) error {
	site := r.sites[id]
	jar, err := cookiejar.New(nil)
	if err != nil {
		return r.wrap(err)
	}
	client := *site.client
	client.Jar = jar
	owner := &installSite{base: site.base, client: &client}
	r.ownerSite[id] = owner
	status, raw, err := owner.post("/api/v1/login", map[string]string{"Email": dcOwnerEmail, "Password": r.fx.password, "Code": ""}, "", "")
	if err = requireSmokeResponse("owner_login", status, 200, raw, err); err != nil {
		return r.wrap(err)
	}
	var s auth.Session
	if err = json.Unmarshal(raw, &s); err != nil {
		return r.wrap(err)
	}
	r.owner[id] = s
	reader, err := loginReader(site, r.fx)
	if err != nil {
		return r.wrap(err)
	}
	r.reader[id] = reader
	return nil
}

func (r *dcRun) nodeFixture(id uint64) *installFixture {
	c := *r.fx
	c.reader = r.reader[id]
	return &c
}

func (r *dcRun) refreshSites(ids ...uint64) error {
	for _, id := range ids {
		site, err := r.cluster.site(id)
		if err != nil {
			return r.wrap(err)
		}
		r.sites[id] = site
	}
	return nil
}

func (r *dcRun) ready(limit time.Duration, ids ...uint64) error {
	for _, id := range ids {
		if err := waitNodeReady(r.sites[id], limit); err != nil {
			return r.wrap(err)
		}
	}
	return nil
}

func (r *dcRun) dir(id uint64) string { return r.cluster.data[id] }

func (r *dcRun) query(id uint64) (int, []byte, error) {
	return queryExpr(r.sites[id], r.nodeFixture(id), r.canary)
}

// poll reads the operation through one node (its own residual view).
func (r *dcRun) poll(id uint64) (httpapi.LifecycleOperation, error) {
	var op httpapi.LifecycleOperation
	status, raw, err := r.ownerSite[id].get("/api/v1/lifecycle/operations/" + r.op.String() + "?org=" + r.fx.org.String())
	if err = requireSmokeResponse("poll_operation", status, 200, raw, err); err != nil {
		return op, err
	}
	if err = json.Unmarshal(raw, &op); err != nil {
		return op, err
	}
	if op.ID != r.op {
		return op, &smokeFailure{Stage: "poll_operation", Code: "wrong_operation"}
	}
	return op, nil
}

func (r *dcRun) scan(id uint64) (dcScan, error) {
	s, err := dcScanDir(r.dir(id), r.canary)
	if err != nil {
		return s, r.wrap(err)
	}
	return s, nil
}

func (r *dcRun) scenario(binary, release string) (result error) {
	started := time.Now()
	lag := r.lag
	r.members = slices.Clone(dcNodes)
	r.watch = lag
	r.live = nil
	for _, id := range dcNodes {
		if id != lag {
			r.live = append(r.live, id)
		}
	}
	via := r.live[0]
	r.art.Evidence["lagging_node"] = lag
	r.art.Evidence["lagging_voter_ending"] = map[bool]string{false: "restarted on its own directory", true: "replaced by a fresh identity (node 4: new raft id, node identity, peer address, certificate, failure domain, empty directory)"}[r.replace]
	r.art.Evidence["replacement_joined_before_the_deletion"] = r.early
	r.art.Evidence["restore_authority_configured"] = r.withAuthority
	r.art.Evidence["deletion_submitted_through_node"] = via
	r.art.Evidence["lagging_node_role"] = map[uint64]string{1: "node 1 is the initial leader of every group (initial_leader: 1); current leadership is not probed by this smoke", 2: "a follower of the initial leader", 3: "a follower of the initial leader"}[lag]
	r.enter("dc_layout")
	work, err := os.MkdirTemp("", "soundpost-delcluster-")
	if err != nil {
		return r.wrap(err)
	}
	defer os.RemoveAll(work)
	cl, err := newProcessCluster(binary, release, work, r.art.Evidence)
	if err != nil {
		return r.wrap(err)
	}
	defer cl.cleanup()
	r.cluster = cl.(*processCluster)
	cfg := cl.installConfig()
	if err = config.Validate(cfg); err != nil {
		return r.wrap(err)
	}
	files, err := config.NodeConfigs(cfg)
	if err != nil {
		return r.wrap(err)
	}
	r.canary = "deletion_cluster_canary_" + strings.ReplaceAll(model.NewID().String(), "-", "")

	r.enter("dc_bootstrap_and_seed")
	fx, seed, err := cl.bootstrap(r.art.Evidence)
	if err != nil {
		return r.wrap(err)
	}
	r.fx = fx
	if err = cl.provision(files, seed); err != nil {
		return r.wrap(err)
	}
	if r.withAuthority {
		r.enter("dc_authority_setup")
		if err = r.setupAuthority(work); err != nil {
			return err
		}
	}

	r.enter("dc_start_three_members")
	if err = r.start(1, 2, 3); err != nil {
		return r.wrap(err)
	}
	if err = r.refreshSites(1, 2, 3); err != nil {
		return err
	}
	r.enter("dc_ready_all")
	if err = r.ready(240*time.Second, 1, 2, 3); err != nil {
		return err
	}
	r.mark("cluster_ready_ms")
	for _, id := range []uint64{1, 2, 3} {
		if err = r.login(id); err != nil {
			return err
		}
	}

	// ---- a sibling project of the same organization, with its own source ----
	r.enter("dc_onboard_sibling_project_through_node_1")
	if err = r.createSibling(1); err != nil {
		return err
	}

	// ---- ingest the canary through node 1 ----
	r.enter("dc_ingest_canary_through_node_1")
	r.fx.queryTime = fmt.Sprint(time.Now().Add(time.Minute).UnixNano())
	resource := model.Resource{Service: fx.service, Environment: fx.environment, Build: fx.build, Instance: "instance", Labels: model.Labels{}}
	for i := 1; i <= dcBatches; i++ {
		value := model.FloatBits(math.Float64bits(float64(i)))
		record := model.Record{ID: model.NewID(), Kind: model.Metric, ObservedAt: model.UnixNano(time.Now().Add(-time.Duration(dcBatches-i) * time.Second).UnixNano()), Resource: resource,
			Payload: model.Payload{Metric: &model.MetricPoint{Name: r.canary, Labels: model.Labels{}, SampleKind: "float", Value: &value, Unit: "1", Type: "gauge"}}}
		batch := model.Batch{Version: 1, Project: fx.project, Source: fx.source, Producer: model.NewID(), ID: model.NewID(), PolicyRevision: 1, Records: []model.Record{record}}
		if batch.RouteSlot, err = model.OwnerSlot(fx.org, fx.project, fx.source, batch.Producer, record); err != nil {
			return r.wrap(err)
		}
		status, raw, _, err := retryIngest(r.sites[1], batch, fx.credential, 120*time.Second)
		if err != nil || status != 200 {
			return r.wrap(requireSmokeResponse("ingest_canary", status, 200, raw, err))
		}
	}
	for i := 1; i <= dcSiblingBatches; i++ {
		if err = r.siblingIngest(1, float64(i)); err != nil {
			return err
		}
	}
	r.mark("ingest_done_ms")
	if err = r.check("ingest_acknowledged", true, strconv.Itoa(dcBatches)+" canary batches and "+strconv.Itoa(dcSiblingBatches)+" sibling batches acknowledged through node 1"); err != nil {
		return err
	}
	for _, id := range []uint64{1, 2, 3} {
		var body []byte
		err = r.until("canary_served_node_"+strconv.FormatUint(id, 10), 120*time.Second, time.Second, func() (bool, string, error) {
			status, raw, err := r.query(id)
			if err != nil {
				return false, "transport", nil
			}
			body = raw
			return dcServedLatest(status, raw, dcBatches), "status_" + strconv.Itoa(status), nil
		})
		if err != nil {
			return err
		}
		if err = r.check("canary_served_node_"+strconv.FormatUint(id, 10), bytes.Contains(body, []byte(r.canary)), "complete answer with the latest value; the canary name is in the body"); err != nil {
			return err
		}
	}
	if err = r.checkSibling("before_deletion", dcNodes...); err != nil {
		return err
	}

	// ---- positive control: the canary is physically present on every node ----
	r.enter("dc_positive_control_live_scan")
	control := map[string]dcScan{}
	siblingControl := map[string]dcScan{}
	for _, id := range []uint64{1, 2, 3} {
		s, err := r.scan(id)
		if err != nil {
			return err
		}
		control[strconv.FormatUint(id, 10)] = s
		if err = r.check("positive_control_canary_present_node_"+strconv.FormatUint(id, 10), s.Hits > 0, fmt.Sprintf("%d hits in %d files, by store %v", s.Hits, s.Files, s.ByStore)); err != nil {
			return err
		}
		m, err := r.scanMarker(id, r.sib.marker)
		if err != nil {
			return err
		}
		siblingControl[strconv.FormatUint(id, 10)] = m
		if err = r.check("positive_control_sibling_marker_present_node_"+strconv.FormatUint(id, 10), m.Hits > 0, fmt.Sprintf("%d hits in %d files, by store %v", m.Hits, m.Files, m.ByStore)); err != nil {
			return err
		}
	}
	r.art.Evidence["live_scan_before_deletion"] = control
	r.art.Evidence["live_scan_sibling_marker_before_deletion"] = siblingControl

	// ---- the lagging voter down, deletion through a live node ----
	if r.auth != nil {
		r.enter("dc_older_backup_and_stop_lagging_voter")
		if err = r.backupWhileDown(lag); err != nil {
			return err
		}
		r.mark("lagging_voter_killed_ms")
	} else {
		r.enter("dc_kill_lagging_voter")
		if err = cl.kill(lag); err != nil {
			return r.wrap(err)
		}
		r.mark("lagging_voter_killed_ms")
	}
	// ---- early learner (replace-early runs): after the older backup (a backup names exactly the three
	// configured voters), the fresh identity joins while the canary is live and holds it when the deletion begins ----
	if r.early {
		if err = r.joinFreshEarly(); err != nil {
			return err
		}
	}
	lagJournal, err := r.journals(lag) // everything the voter will ever have journaled before it is brought back
	if err != nil {
		return err
	}
	r.art.Evidence["lagging_voter_journals_at_kill"] = lagJournal
	if err = r.ready(120*time.Second, r.live...); err != nil {
		return err
	}
	if err = r.login(via); err != nil { // fresh reauthentication: a deletion needs a session younger than 5 minutes
		return err
	}
	r.enter("dc_begin_deletion_lagging_voter_down")
	var receipt httpapi.DeletionReceipt
	command := model.NewID()
	err = r.until("begin_deletion", 90*time.Second, time.Second, func() (bool, string, error) {
		status, raw, err := r.ownerSite[via].post("/api/v1/admin/read", struct {
			Kind string `json:"kind"`
		}{"organizations"}, r.owner[via].CSRF, "")
		if err != nil || status != 200 {
			return false, "admin_read_" + strconv.Itoa(status), nil
		}
		var view auth.AdminView
		if err = json.Unmarshal(raw, &view); err != nil {
			return false, "", err
		}
		status, raw, err = r.ownerSite[via].post("/api/v1/admin/deletions", httpapi.DeletionRequest{CommandID: command, ExpectedRevision: model.Uint64(view.Revision), Mode: model.DeleteRetireProject,
			OrgID: fx.org, ProjectIDs: []model.ID{fx.project}, Reason: "deletion-cluster smoke"}, r.owner[via].CSRF, "")
		if err != nil {
			return false, "transport", nil
		}
		switch status {
		case http.StatusAccepted:
			return true, "accepted", json.Unmarshal(raw, &receipt)
		case http.StatusConflict:
			var refused httpapi.DeletionRefused
			if json.Unmarshal(raw, &refused) == nil && refused.Detail != "" {
				return false, "", httpSmokeFailure("begin_deletion", status, http.StatusAccepted, raw)
			}
			return false, "stale_revision", nil // the revision moved between the read and the commit: read again
		case http.StatusServiceUnavailable:
			return false, "status_503", nil
		default:
			return false, "", httpSmokeFailure("begin_deletion", status, http.StatusAccepted, raw)
		}
	})
	if err != nil {
		return err
	}
	r.op = receipt.OperationID
	r.mark("deletion_begun_ms")
	if err = r.check("begin_answers_fencing_202", receipt.Phase == model.DeletePhaseFencing && receipt.Mode == model.DeleteRetireProject, "phase "+safeToken(receipt.Phase)+" mode "+safeToken(receipt.Mode)); err != nil {
		return err
	}
	status, raw, qerr := r.query(via)
	if qerr != nil {
		return r.wrap(qerr)
	}
	if err = r.check("reads_denied_at_begin_node_"+dcKey(via), dcDenied(status, raw) && !bytes.Contains(raw, []byte(r.canary)), fmt.Sprintf("status %d code %s", status, dcFaultCode(raw))); err != nil {
		return err
	}
	if r.replace {
		return r.replaceWhilePending(started)
	}

	r.enter("dc_wait_complete_lagging_voter_down")
	complete := map[uint64]httpapi.LifecycleOperation{}
	for _, id := range r.live {
		if id != via {
			if err = r.login(id); err != nil {
				return err
			}
		}
		err = r.until("operation_complete_node_"+strconv.FormatUint(id, 10), r.wait, dcPollInterval, func() (bool, string, error) {
			op, err := r.poll(id)
			if err != nil {
				var sf *smokeFailure
				if errors.As(err, &sf) && sf.Actual >= 500 {
					return false, "status_" + strconv.Itoa(sf.Actual), nil
				}
				return false, "", err
			}
			complete[id] = op
			return op.Phase == model.DeletePhaseComplete && op.Physical == "done", "phase_" + safeToken(op.Phase) + "_physical_" + safeToken(op.Physical), nil
		})
		if err != nil {
			return err
		}
		r.mark("complete_seen_node_" + strconv.FormatUint(id, 10) + "_ms")
	}
	if err = r.check("operation_complete_while_lagging_voter_down", true, "phase complete and physical done on both live nodes"); err != nil {
		return err
	}
	if r.auth != nil {
		r.enter("dc_authority_checkpointed_deletion")
		if err = r.checkAuthority(); err != nil {
			return err
		}
	}

	// ---- the sibling project is untouched while the deletion is pending and the voter is down ----
	r.enter("dc_sibling_untouched_lagging_voter_down")
	if err = r.siblingIngest(via, float64(dcSiblingBatches+1)); err != nil {
		return err
	}
	if err = r.check("sibling_ingest_accepted_after_deletion_complete", true, "a new sample for the sibling project acknowledged through node "+dcKey(via)); err != nil {
		return err
	}
	if err = r.checkSibling("while_lagging_down", r.live...); err != nil {
		return err
	}

	r.enter("dc_receipt_names_data_apply_db_lagging_voter_down")
	samples := map[string]int{}
	seen := map[string][]string{}
	holdUntil := time.Now().Add(r.hold)
	for first := true; first || time.Now().Before(holdUntil); first = false {
		for _, id := range r.live {
			op, err := r.poll(id)
			if err != nil {
				return r.wrap(err)
			}
			key := strconv.FormatUint(id, 10)
			samples[key]++
			seen[key] = op.ResidualStores
			ok := op.Phase == model.DeletePhaseComplete && op.Physical == "done" && dcNamesApplyDB(op.ResidualStores)
			if err = r.check("receipt_names_data_apply_db_node_"+key+"_while_lagging_voter_down", ok, fmt.Sprintf("sample %d: phase %s physical %s residual %v", samples[key], safeToken(op.Phase), safeToken(op.Physical), op.ResidualStores)); err != nil {
				return err
			}
		}
		if time.Now().Before(holdUntil) {
			time.Sleep(dcPollInterval)
		}
	}
	r.art.Evidence["receipt_while_lagging_voter_down"] = map[string]any{"samples": samples, "last_residual_stores": seen}
	r.mark("lagging_voter_down_receipt_checked_ms")

	// ---- the journals of the live voters are cut past the lagging voter: it can only install a snapshot ----
	// The retention worker of each live voter erases its copy, cuts a verified snapshot of every
	// group and truncates each journal to it (maintainJournal) before the voter marks the
	// operation erased. This smoke waits for that on every live voter (their files hold no canary
	// any more) and then reads what their journals and the lagging voter's journals say.
	r.enter("dc_live_voters_erased_and_journals_cut")
	liveDown := map[string]dcScan{}
	err = r.until("live_voters_hold_no_canary", r.wait, dcPollInterval, func() (bool, string, error) {
		dirty := []string{}
		for _, id := range r.live {
			s, err := r.scan(id)
			if err != nil {
				return false, "", err
			}
			liveDown[dcKey(id)] = s
			if s.Hits > 0 {
				dirty = append(dirty, fmt.Sprintf("node_%d:%d_hits_%v", id, s.Hits, s.ByStore))
			}
		}
		return len(dirty) == 0, strings.Join(dirty, " "), nil
	})
	if err != nil {
		return err
	}
	r.art.Evidence["live_scan_live_voters_before_lagging_voter_restart"] = liveDown
	cut := map[string]dcJournal{} // per journal, the lowest cut among the live voters that cut past the lagging voter
	for _, id := range r.live {
		jr, err := r.journals(id)
		if err != nil {
			return err
		}
		past := dcStranded(lagJournal, jr)
		for _, name := range past {
			if c, ok := cut[name]; !ok || jr[name].Snapshot < c.Snapshot {
				cut[name] = jr[name]
			}
		}
		if err = r.check("journal_cut_past_lagging_voter_node_"+dcKey(id), len(past) > 0, fmt.Sprintf("%d of %d journals start after an index the lagging voter never journaled", len(past), len(jr))); err != nil {
			return err
		}
	}
	stranded := make([]string, 0, len(cut))
	for name := range cut {
		stranded = append(stranded, name)
	}
	sort.Strings(stranded)
	r.art.Evidence["journals_the_lagging_voter_can_only_catch_up_by_snapshot"] = stranded
	r.mark("live_voters_cut_ms")

	// ---- the lagging voter back: it must install a snapshot, and no receipt may read clean before it erased again ----
	r.enter("dc_restart_lagging_voter")
	if err = r.start(lag); err != nil {
		return r.wrap(err)
	}
	r.mark("lagging_voter_restarted_ms")
	if err = r.refreshSites(lag); err != nil {
		return err
	}
	track := newDCCleanTrack()
	err = r.until("lagging_voter_ready", 240*time.Second, 10*time.Millisecond, func() (bool, string, error) {
		if _, err := r.sample(track, r.live...); err != nil {
			return false, "", err
		}
		if err := waitNodeReady(r.sites[lag], time.Second); err != nil {
			return false, "not_ready", nil
		}
		return true, "", nil
	})
	if err != nil {
		return err
	}
	r.mark("lagging_voter_ready_ms")
	if err = r.login(lag); err != nil {
		return err
	}
	r.enter("dc_wait_receipt_clean_all_nodes")
	err = r.until("receipt_clean_all_nodes", r.wait, dcPollInterval, func() (bool, string, error) {
		progress, err := r.sample(track, dcNodes...)
		if err != nil {
			return false, "", err
		}
		return len(track.cleanAt) == len(dcNodes) && len(progress) == 0, "not_clean " + strings.Join(progress, " "), nil
	})
	if err != nil {
		return err
	}
	r.art.Evidence["live_scan_at_first_clean_receipt"] = track.own
	r.art.Evidence["lagging_voter_scan_at_first_clean_receipt"] = track.lagging
	r.art.Evidence["receipt_residual_trail_after_lagging_voter_restart"] = track.trail
	r.art.Evidence["receipt_samples_after_lagging_voter_restart"] = track.samples
	r.art.Evidence["receipt_not_clean_samples_after_lagging_voter_restart"] = track.notClean
	if err = r.check("receipt_clean_on_all_three_nodes", true, "phase complete, physical done, no residual store on nodes 1, 2 and 3"); err != nil {
		return err
	}
	for _, id := range dcNodes {
		key := dcKey(id)
		if err = r.check("live_scan_zero_when_receipt_first_clean_node_"+key, track.own[key].Hits == 0, fmt.Sprintf("%d hits in %d files, by store %v", track.own[key].Hits, track.own[key].Files, track.own[key].ByStore)); err != nil {
			return err
		}
	}
	// ---- the lagging voter moved past every journal the others cut: that is an installed snapshot ----
	r.enter("dc_lagging_voter_installed_snapshot")
	var passed []string
	err = r.until("lagging_voter_journals_past_the_cut", r.wait, dcPollInterval, func() (bool, string, error) {
		now, err := r.journals(lag)
		if err != nil {
			return false, "", err
		}
		passed = dcInstalledPast(stranded, cut, now)
		return len(passed) == len(stranded), fmt.Sprintf("%d of %d", len(passed), len(stranded)), nil
	})
	if err != nil {
		return err
	}

	return r.stopRestartVerify(started, "lagging_voter", stranded, cut, lag, true)
}

// scanAll scans every node's data directory (the processes are stopped) and requires zero
// hits on each; the per-node result is kept in the artifact either way.
func (r *dcRun) scanAll(evidence, stage string) error {
	r.enter(stage)
	results := map[string]dcScan{}
	ids := slices.Clone(r.members)
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
	var failed error
	for _, id := range ids {
		s, err := r.scan(id)
		if err != nil {
			return err
		}
		key := strconv.FormatUint(id, 10)
		results[key] = s
		detail := fmt.Sprintf("%d hits in %d files (%d bytes); by store %v; files %v", s.Hits, s.Files, s.Bytes, s.ByStore, s.HitFiles)
		if err = r.check(evidence+"_zero_hits_node_"+key, s.Hits == 0, detail); err != nil && failed == nil {
			failed = err
		}
	}
	r.art.Evidence[evidence] = results
	if failed != nil {
		return failed
	}
	// The sibling project's marker must still be in every node's files: erasing the retired
	// project took nothing of the sibling's bytes with it.
	sibling := map[string]dcScan{}
	for _, id := range ids {
		s, err := r.scanMarker(id, r.sib.marker)
		if err != nil {
			return err
		}
		key := dcKey(id)
		sibling[key] = s
		if err = r.check(evidence+"_sibling_marker_present_node_"+key, s.Hits > 0, fmt.Sprintf("%d hits in %d files; by store %v", s.Hits, s.Files, s.ByStore)); err != nil {
			return err
		}
	}
	r.art.Evidence[evidence+"_sibling_marker"] = sibling
	return nil
}

// freshBatch is a well-formed batch for the retired project, never acknowledged.
func (r *dcRun) freshBatch() model.Batch {
	fx := r.fx
	value := model.FloatBits(math.Float64bits(99))
	record := model.Record{ID: model.NewID(), Kind: model.Metric, ObservedAt: model.UnixNano(time.Now().UnixNano()), Resource: model.Resource{Service: fx.service, Environment: fx.environment, Build: fx.build, Instance: "instance", Labels: model.Labels{}},
		Payload: model.Payload{Metric: &model.MetricPoint{Name: r.canary, Labels: model.Labels{}, SampleKind: "float", Value: &value, Unit: "1", Type: "gauge"}}}
	batch := model.Batch{Version: 1, Project: fx.project, Source: fx.source, Producer: model.NewID(), ID: model.NewID(), PolicyRevision: 1, Records: []model.Record{record}}
	batch.RouteSlot, _ = model.OwnerSlot(fx.org, fx.project, fx.source, batch.Producer, record)
	return batch
}

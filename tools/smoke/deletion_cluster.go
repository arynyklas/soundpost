// RunDeletionCluster drives the per-voter erasure of a deletion through THREE REAL
// `soundpost serve --mode=distributed` processes (the produced static binary, one data
// directory each, the cluster configuration generated by internal/config, exactly as
// install-distributed provisions them):
//
//  1. onboard a source and ingest batches carrying a canary metric name into one project
//     through node 1; every node serves the canary; a live scan of every node's data
//     directory finds it (the positive control: a zero later means something);
//  2. kill node 3, then begin retire_project through node 1 with a freshly authenticated
//     organization-admin session (POST /api/v1/admin/deletions) and poll
//     GET /api/v1/lifecycle/operations/{id} until the operation is complete with its
//     physical step done;
//  3. while node 3 is down the receipt on nodes 1 and 2 must keep naming data_apply_db
//     (a lagging voter keeps the receipt from calling the data clean), sampled for a hold
//     window;
//  4. restart node 3; wait until the receipt on all three nodes is clean (no residual
//     store at all);
//  5. STOP each node (SIGTERM) and scan every regular file of its data directory (apply.db,
//     segments, Raft journals, snapshots, control.db, everything) for the canary through
//     the same nested base64 decoder the in-process deletion smoke uses: zero hits on every
//     node;
//  6. restart all three: the receipt stays clean, the project's data is denied through each
//     node (reader query, source ingest), and a second scan after another stop is still zero.
//
// Every wait is bounded; a timeout is a typed smokeFailure carrying the stage name. The JSON
// artifact (deletion-cluster.json in --artifact-dir) is written on success AND on failure
// and lists each assertion, every stage duration and named milestone timings. It never
// contains the canary, a credential or a session token.
//
// This is a loopback-process simulation: three directories on one host, not three physical
// failure domains, and no power-loss or distinct-hardware qualification.
//
// Registered as: case "deletion-cluster": return RunDeletionCluster(os.Args[2:]).
func RunDeletionCluster(args []string) (result error) {
	rec := newDCRecorder()
	defer func() {
		result = rec.finish(result)
	}()
	rec.enter("dc_flags")
	f := flag.NewFlagSet("deletion-cluster", flag.ContinueOnError)
	f.SetOutput(io.Discard)
	artifact := f.String("artifact-dir", "", "sanitized result directory")
	binary := f.String("binary", "", "produced static soundpost binary (three processes)")
	release := f.String("release", "", "release directory the binary must belong to")
	wait := f.Duration("wait", 6*time.Minute, "bound of every deletion wait (the retention worker passes once a minute)")
	hold := f.Duration("hold-window", 20*time.Second, "how long nodes 1 and 2 are sampled while node 3 is down")
	if err := f.Parse(args); err != nil {
		return rec.wrap(err)
	}
	if *artifact == "" || *binary == "" || *wait <= 0 || *hold < 0 {
		return rec.wrap(errors.New("--artifact-dir and --binary are required, --wait must be positive"))
	}
	rec.artifactDir = *artifact
	if err := os.MkdirAll(*artifact, 0o700); err != nil {
		return rec.wrap(err)
	}
	r := &dcRun{dcRecorder: rec, wait: *wait, hold: *hold, sites: map[uint64]*installSite{}, ownerSite: map[uint64]*installSite{}, owner: map[uint64]auth.Session{}, reader: map[uint64]auth.Session{}}
	return r.scenario(*binary, *release)
}


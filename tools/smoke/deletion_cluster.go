// RunDeletionCluster drives the per-voter erasure of a deletion through THREE REAL
// `soundpost serve --mode=distributed` processes (the produced static binary, one data
// directory each, the cluster configuration generated by internal/config, exactly as
// install-distributed provisions them). Every run is a fresh cluster with its own artifact and
// one voter held back: --lag-nodes (default 3,2,1: a follower, the other follower, then node 1,
// the initial leader of every group) restarts it (deletion-cluster-lag-<N>.json), --replace-nodes
// (default 3) replaces it by a fresh identity (deletion-cluster-replace-<N>.json); "none" drops
// one kind. Unless --authority=false every serve process is given a REAL restore authority (its
// own directory and signing keys, outside every node's data directory):
//
//  0. authority: `backup authority-keygen`, `authority-init` against the stopped bootstrap
//     installation the cluster is seeded from, `backup keygen` for the two key-encryption keys;
//     every serve process gets --authority-keys (full keys) and --authority-dir;
//  1. onboard a source and ingest batches carrying a canary metric name into one project
//     through node 1, and a SIBLING project of the same organization (its own source, reader
//     grant and marker metric); every node serves both; a live scan of every node's data
//     directory finds the canary and the sibling marker (the positive control: a zero later
//     means something);
//  2. stop the lagging voter (SIGTERM) and, with the other two holding the quorum, take an OLDER
//     BACKUP of the cluster through its directory (`backup create --mode distributed`: the canary
//     is in it); without an authority the voter is killed instead. Then begin retire_project
//     through a live node with a freshly authenticated organization-admin session
//     (POST /api/v1/admin/deletions) and poll GET /api/v1/lifecycle/operations/{id} until the
//     operation is complete with its physical step done; the authority, read directly with the
//     restricted keys, holds the tombstone of exactly that project at a head past the backup's; the
//     sibling project keeps serving its data and its control rows (project, reader grant, live
//     source) through the real query and administrator read APIs and accepts a new sample;
//
// Restart runs (--lag-nodes) continue:
//
//  3. while the voter is down the receipt on the live nodes must keep naming data_apply_db (a
//     lagging voter keeps the receipt from calling the data clean), sampled for a hold window;
//  4. FORCED SNAPSHOT INSTALL: wait until both live voters hold no canary in any file (their
//     retention workers erased, cut a verified snapshot of every group and truncated each Raft
//     journal to it), then require, from the journal files, that on each live voter some group's
//     journal starts after an index the lagging voter never journaled: the entries between are gone,
//     so that voter can only be brought up to date by installing a snapshot;
//  5. restart the voter; from the moment it starts, sample the receipt on every node: a receipt
//     that reads clean while the lagging voter's own directory still holds the canary is a false
//     clean (checked at every clean answer), and the residual-store trail is recorded; wait until
//     the receipt on all three nodes is clean (no residual store at all);
//  6. STOP each node (SIGTERM). The lagging voter's own journals must now start past every cut
//     the live voters made while it was down (only an installed snapshot gets a voter past entries
//     nobody holds), and the replicated erase notice that names the voter (which the sending voter
//     commits before it announces a snapshot) must be in every node's apply.db. Scan every regular
//     file of every data directory (apply.db, segments, Raft journals, snapshots, control.db,
//     everything) for the canary through the same nested base64 decoder the in-process deletion
//     smoke uses: zero hits on every node; and for the sibling marker: still present on every node;
//  7. restart all three: the receipt stays clean, the retired project's data is denied through each
//     node (reader query, source ingest), the sibling's data and control rows are intact through each
//     node and a new sibling sample is acknowledged through the formerly lagging voter, and a
//     second scan after another stop is still zero for the canary and still positive for the
//     sibling.
//
// Replacement runs (--replace-nodes) instead, right after the deletion was begun and while it is
// pending (the leaders' state still holds the canary, no receipt can be clean), REPLACE the dead
// voter through the product's membership path (docs/operations/distributed.md, "Replacing a
// voter"): `membership add-learner` for node 4 (new raft id, node identity, peer address,
// certificate, failure domain), start it on an EMPTY directory, `membership replace --remove N
// --promote 4`. The receipt is sampled from before the learner exists: a clean answer while node
// 4's directory holds the canary is a false clean, node 4's directory is scanned throughout (the
// canary must be gone from it before the first clean answer), the receipt must end clean on every
// member, then steps 6 and 7 run over members {the two live voters, node 4}. The retired voter's
// directory (never started again) still holds the canary and is outside every receipt: that is
// asserted as a fact, not hidden.
//
// Early-learner replacement runs (--replace-early-nodes, default none) add the fresh identity as a
// learner BEFORE the deletion, while the canary is live, and wait until the learner's own directory
// holds the canary; only then is the lagging voter stopped and the deletion begun. The replacement
// therefore HOLDS the canary when the deletion is pending (a late join only ever receives erased
// state): no receipt may read clean while the learner's directory holds it, and the learner must have
// erased it before the first clean receipt (deletion-cluster-replace-early-<N>.json).
//
// Last (with an authority), the OLDER backup is restored: `backup restore` into a clean root
// against the CURRENT authority (it must verify the head past the backup and carry the tombstone),
// `backup activate`, and the restored root is served by a real process. The recovery
// administrator (bootstrap token of the restored root) reinstates the reader's account, membership
// and sibling grant; the retired project's grant cannot be reinstated, its read and ingest are
// denied and the sibling's data is served as of the backup. The deletion must not come back: the
// older backup held the canary, and the restored installation's own retention worker erases its
// copy (the canary leaves the restored root) while the sibling marker stays.
//
// Every wait is bounded; a timeout is a typed smokeFailure carrying the stage name. The JSON
// artifact (deletion-cluster-lag-<N>.json or deletion-cluster-replace-<N>.json in --artifact-dir)
// is written on success AND on failure and lists each assertion, every stage duration and named
// milestone timings. It never contains the canary, a credential or a session token.
//
// This is a loopback-process simulation: three directories on one host, not three physical
// failure domains, and no power-loss or distinct-hardware qualification; the authority is a
// directory of this host, not separate hardware.
//
// Registered as: case "deletion-cluster": return RunDeletionCluster(os.Args[2:]).
func RunDeletionCluster(args []string) error {
	rec := newDCRecorder()
	rec.enter("dc_flags")
	f := flag.NewFlagSet("deletion-cluster", flag.ContinueOnError)
	f.SetOutput(io.Discard)
	artifact := f.String("artifact-dir", "", "sanitized result directory")
	binary := f.String("binary", "", "produced static soundpost binary (three processes)")
	release := f.String("release", "", "release directory the binary must belong to")
	wait := f.Duration("wait", 6*time.Minute, "bound of every deletion wait (the retention worker passes once a minute)")
	hold := f.Duration("hold-window", 20*time.Second, "how long the live nodes are sampled while the lagging voter is down")
	lagNodes := f.String("lag-nodes", "3,2,1", "comma-separated voters to hold back and restart, one full run each (node 1 is the initial leader); none: no such run")
	replaceNodes := f.String("replace-nodes", "3", "comma-separated voters to hold back and replace by a fresh identity, one full run each; none: no such run")
	authority := f.Bool("authority", true, "give every serve process a real restore authority (own directory and keys), take an older backup before the deletion and restore it after")
	replaceEarlyNodes := f.String("replace-early-nodes", "none", "comma-separated voters to hold back and replace by a fresh identity that joined as a learner BEFORE the deletion and holds the canary, one full run each; none: no such run")
	if err := f.Parse(args); err != nil {
		return rec.finish(rec.wrap(err))
	}
	plan, err := dcPlan(*lagNodes, *replaceNodes, *replaceEarlyNodes)
	if err != nil {
		return rec.finish(rec.wrap(err))
	}
	if *artifact == "" || *binary == "" || *wait <= 0 || *hold < 0 {
		return rec.finish(rec.wrap(errors.New("--artifact-dir and --binary are required, --wait must be positive")))
	}
	if err = os.MkdirAll(*artifact, 0o700); err != nil {
		return rec.finish(rec.wrap(err))
	}
	for _, step := range plan {
		run := newDCRecorder()
		run.artifactDir, run.file = *artifact, dcRunArtifactName(step)
		run.art.NotRun = dcNotRun(*authority, step.Replace)
		r := &dcRun{dcRecorder: run, wait: *wait, hold: *hold, lag: step.Node, replace: step.Replace, early: step.Early, withAuthority: *authority, sites: map[uint64]*installSite{}, ownerSite: map[uint64]*installSite{}, owner: map[uint64]auth.Session{}, reader: map[uint64]auth.Session{}}
		if err = run.finish(r.scenario(*binary, *release)); err != nil {
			return err
		}
	}
	return nil
}


// ---- recorder: assertions, stages, timings, the typed failure, the artifact ----

type dcAssertion struct {
	Name   string `json:"name"`
	Stage  string `json:"stage"`
	OK     bool   `json:"ok"`
	Detail string `json:"detail,omitempty"`
	AtMS   int64  `json:"at_ms"`
}

type dcStage struct {
	Name       string `json:"name"`
	DurationMS int64  `json:"duration_ms"`
}

type dcFailure struct {
	Stage  string `json:"stage"`
	Code   string `json:"code"`
	Detail string `json:"detail,omitempty"`
}

type dcArtifact struct {
	Version     int              `json:"version"`
	Smoke       string           `json:"smoke"`
	Caveat      string           `json:"caveat"`
	Result      string           `json:"result"`
	Failure     *dcFailure       `json:"failure,omitempty"`
	StartedAt   string           `json:"started_at"`
	WallClockMS int64            `json:"wall_clock_ms"`
	Stages      []dcStage        `json:"stages"`
	Assertions  []dcAssertion    `json:"assertions"`
	TimingsMS   map[string]int64 `json:"timings_ms"`
	Evidence    map[string]any   `json:"evidence"`
	NotRun      []string         `json:"not_run"`
}

type dcRecorder struct {
	started      time.Time
	stage        string
	stageStarted time.Time
	detail       string
	artifactDir  string
	art          dcArtifact
}

func newDCRecorder() *dcRecorder {
	now := time.Now()
	return &dcRecorder{started: now, art: dcArtifact{
		Version: 1, Smoke: dcSmoke, Result: "failed", StartedAt: now.UTC().Format(time.RFC3339),
		Caveat:    "loopback-process simulation on one host: NOT three physical failure domains, no power-loss or distinct-hardware qualification",
		TimingsMS: map[string]int64{}, Evidence: map[string]any{},
		NotRun: []string{
			"three independent physical hosts, disks, power or network paths",
			"a sibling project in the same cluster (bootstrapInstallation creates one project; over-erasure of a sibling is covered by the in-process delete-restore-pressure smoke)",
			"off-host backup authority and restore (no backup authority is configured: backup mode none)",
			"container host (--binary processes only)",
		},
	}}
}

func (r *dcRecorder) since() int64 { return time.Since(r.started).Milliseconds() }

// enter closes the running stage and opens the next.
func (r *dcRecorder) enter(name string) {
	r.closeStage()
	r.stage, r.stageStarted = name, time.Now()
}

func (r *dcRecorder) closeStage() {
	if r.stage != "" {
		r.art.Stages = append(r.art.Stages, dcStage{Name: r.stage, DurationMS: time.Since(r.stageStarted).Milliseconds()})
		r.stage = ""
	}
}

// mark records a named milestone as milliseconds since the start.
func (r *dcRecorder) mark(name string) { r.art.TimingsMS[name] = r.since() }

// check records one assertion; a false one is the typed failure (code = assertion name).
func (r *dcRecorder) check(name string, ok bool, detail string) error {
	r.art.Assertions = append(r.art.Assertions, dcAssertion{Name: name, Stage: r.stage, OK: ok, Detail: detail, AtMS: r.since()})
	if ok {
		return nil
	}
	r.detail = detail
	return &smokeFailure{Smoke: dcSmoke, Stage: r.stage, Code: name}
}

// wrap turns any helper error into a typed failure that names THIS smoke's stage; the helper's
// own stage and code are folded into the code, so nothing from a request or response leaks.
func (r *dcRecorder) wrap(err error) error {
	if err == nil {
		return nil
	}
	var inner *smokeFailure
	if errors.As(err, &inner) {
		code := inner.Code
		if inner.Smoke == dcSmoke {
			return inner
		}
		if inner.Stage != "" {
			code = inner.Stage + "_" + inner.Code
		}
		return &smokeFailure{Smoke: dcSmoke, Stage: r.stage, Code: code, Actual: inner.Actual, Expected: inner.Expected}
	}
	return &smokeFailure{Smoke: dcSmoke, Stage: r.stage, Code: classifySmokeError(err)}
}

// until polls fn every interval until it reports done, fails, or limit passes. A timeout is
// the typed failure {stage, timeout_<what>}; the last progress text is kept as its detail.
func (r *dcRecorder) until(what string, limit, interval time.Duration, fn func() (done bool, progress string, err error)) error {
	deadline := time.Now().Add(limit)
	last := "no_poll"
	for {
		done, progress, err := fn()
		if err != nil {
			return r.wrap(err)
		}
		if progress != "" {
			last = progress
		}
		if done {
			return nil
		}
		if !time.Now().Before(deadline) {
			r.detail = what + ": " + last
			return &smokeFailure{Smoke: dcSmoke, Stage: r.stage, Code: "timeout_" + what}
		}
		time.Sleep(interval)
	}
}

// finish closes the stage list, classifies the result and writes the artifact. A failure to
// write the artifact is an error of its own only when the run itself passed.
func (r *dcRecorder) finish(err error) error {
	failedStage := r.stage
	r.closeStage()
	r.art.WallClockMS = r.since()
	if err == nil {
		r.art.Result = "passed"
	} else {
		var typed *smokeFailure
		if !errors.As(err, &typed) {
			typed = &smokeFailure{Smoke: dcSmoke, Stage: failedStage, Code: classifySmokeError(err)}
			err = typed
		}
		r.art.Failure = &dcFailure{Stage: typed.Stage, Code: typed.Code, Detail: r.detail}
	}
	if r.artifactDir == "" {
		return err
	}
	raw, mErr := json.MarshalIndent(r.art, "", "  ")
	if mErr == nil {
		mErr = os.WriteFile(filepath.Join(r.artifactDir, "deletion-cluster.json"), append(raw, '\n'), 0o600)
	}
	if mErr != nil && err == nil {
		return &smokeFailure{Smoke: dcSmoke, Stage: "dc_artifact", Code: "write_failed"}
	}
	return err
}

// ---- the physical scan ----

// dcScan is what a whole-file scan of one node's data directory found.
type dcScan struct {
	Files    int            `json:"files"`
	Bytes    int64          `json:"bytes"`
	Hits     int            `json:"hits"`
	ByStore  map[string]int `json:"hits_by_store"`
	HitFiles map[string]int `json:"hit_files,omitempty"`
}

// dcStoreOf names the store class of a data-directory path (relative, slash-separated).
func dcStoreOf(rel string) string {
	rel = filepath.ToSlash(rel)
	base := path.Base(rel)
	switch {
	case strings.Contains(rel, "/snapshots/") || strings.HasPrefix(rel, "snapshots/"):
		return "snapshots"
	case base == "apply.db":
		return "apply_db"
	case strings.Contains(rel, "/segments/") || strings.HasPrefix(rel, "segments/"):
		return "segments"
	case strings.HasPrefix(base, "control.db"):
		return "control_db"
	case strings.HasSuffix(base, ".wal") || strings.Contains(rel, "raft/") || strings.HasPrefix(rel, "raft"):
		return "raft_journal"
	default:
		return "other"
	}
}

// dcScanDir reads every regular file of dir whole and counts the canary in it and in
// everything that decodes out of it (journals and snapshots wrap commands in base64 inside
// JSON inside base64, so a plain byte search would prove nothing about them).
func dcScanDir(dir, canary string) (dcScan, error) {
	out := dcScan{ByStore: map[string]int{}, HitFiles: map[string]int{}}
	needle := []byte(canary)
	err := filepath.Walk(dir, func(p string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || !info.Mode().IsRegular() {
			return err
		}
		raw, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(dir, p)
		rel = filepath.ToSlash(rel)
		hits := map[string]int{}
		deepHits(raw, needle, 5, "raw", hits)
		n := sum(hits)
		out.Files++
		out.Bytes += int64(len(raw))
		if n > 0 {
			out.Hits += n
			out.ByStore[dcStoreOf(rel)] += n
			out.HitFiles[rel] = n
		}
		return nil
	})
	return out, err
}

// ---- receipts, denial, canary query ----

// dcNamesApplyDB reports whether a receipt still names the data store as owed.
func dcNamesApplyDB(residual []string) bool {
	return slices.Contains(residual, storage.ResidualApplyDB)
}

// dcDenied classifies an answer to a read or an ingest of the retired project. It is denial
// when the server answered with a typed 4xx fault, or with 200 whose project carries a
// failure; a 5xx, a transport error or a served value is not.
func dcDenied(status int, raw []byte) bool {
	if status >= 400 && status < 500 {
		return true
	}
	if status != http.StatusOK {
		return false
	}
	var result query.Result
	if json.Unmarshal(raw, &result) != nil || len(result.Projects) == 0 {
		return false
	}
	for _, p := range result.Projects {
		if p.Failure == nil || p.Value != nil {
			return false
		}
	}
	return true
}

// dcFaultCode is the typed fault code of an error answer ("" when there is none).
func dcFaultCode(raw []byte) string {
	var f struct {
		Code string `json:"code"`
	}
	if json.Unmarshal(raw, &f) != nil {
		return ""
	}
	return safeToken(f.Code)
}

// dcServedLatest reports whether a query answer is a complete single sample equal to want.
func dcServedLatest(status int, raw []byte, want float64) bool {
	if status != http.StatusOK {
		return false
	}
	var result query.Result
	if json.Unmarshal(raw, &result) != nil || len(result.Projects) != 1 {
		return false
	}
	p := result.Projects[0]
	if p.Failure != nil || p.Completeness != query.CompletenessComplete || p.Value == nil || p.Value.Type != query.ValueVector || len(p.Value.Vector) != 1 || p.Value.Vector[0].Sample.Float == nil {
		return false
	}
	return math.Float64frombits(uint64(*p.Value.Vector[0].Sample.Float)) == want
}


type dcRun struct {
	*dcRecorder
	wait, hold time.Duration
	cluster    *processCluster
	fx         *installFixture
	sites      map[uint64]*installSite // reader-side client per node (its own cookie jar)
	ownerSite  map[uint64]*installSite // organization-owner client per node (its own cookie jar)
	owner      map[uint64]auth.Session
	reader     map[uint64]auth.Session
	canary     string
	op         model.ID
}

// login opens an owner session and a reader session on one node. They use separate clients:
// both sessions ride the same cookie name, so one jar would hold only the later login.
func (r *dcRun) login(id uint64) error {
	site := r.sites[id]
	jar, err := cookiejar.New(nil)
	if err != nil {
		return r.wrap(err)
	}
	client := *site.client
	client.Jar = jar
	owner := &installSite{base: site.base, client: &client}
	r.ownerSite[id] = owner
	status, raw, err := owner.post("/api/v1/login", map[string]string{"Email": dcOwnerEmail, "Password": r.fx.password, "Code": ""}, "", "")
	if err = requireSmokeResponse("owner_login", status, 200, raw, err); err != nil {
		return r.wrap(err)
	}
	var s auth.Session
	if err = json.Unmarshal(raw, &s); err != nil {
		return r.wrap(err)
	}
	r.owner[id] = s
	reader, err := loginReader(site, r.fx)
	if err != nil {
		return r.wrap(err)
	}
	r.reader[id] = reader
	return nil
}

func (r *dcRun) nodeFixture(id uint64) *installFixture {
	c := *r.fx
	c.reader = r.reader[id]
	return &c
}

func (r *dcRun) refreshSites(ids ...uint64) error {
	for _, id := range ids {
		site, err := r.cluster.site(id)
		if err != nil {
			return r.wrap(err)
		}
		r.sites[id] = site
	}
	return nil
}

func (r *dcRun) ready(limit time.Duration, ids ...uint64) error {
	for _, id := range ids {
		if err := waitNodeReady(r.sites[id], limit); err != nil {
			return r.wrap(err)
		}
	}
	return nil
}

func (r *dcRun) dir(id uint64) string { return r.cluster.data[id] }

func (r *dcRun) query(id uint64) (int, []byte, error) {
	return queryExpr(r.sites[id], r.nodeFixture(id), r.canary)
}

// poll reads the operation through one node (its own residual view).
func (r *dcRun) poll(id uint64) (httpapi.LifecycleOperation, error) {
	var op httpapi.LifecycleOperation
	status, raw, err := r.ownerSite[id].get("/api/v1/lifecycle/operations/" + r.op.String() + "?org=" + r.fx.org.String())
	if err = requireSmokeResponse("poll_operation", status, 200, raw, err); err != nil {
		return op, err
	}
	if err = json.Unmarshal(raw, &op); err != nil {
		return op, err
	}
	if op.ID != r.op {
		return op, &smokeFailure{Stage: "poll_operation", Code: "wrong_operation"}
	}
	return op, nil
}

func (r *dcRun) scan(id uint64) (dcScan, error) {
	s, err := dcScanDir(r.dir(id), r.canary)
	if err != nil {
		return s, r.wrap(err)
	}
	return s, nil
}

func (r *dcRun) scenario(binary, release string) (result error) {
	started := time.Now()
	r.enter("dc_layout")
	work, err := os.MkdirTemp("", "soundpost-delcluster-")
	if err != nil {
		return r.wrap(err)
	}
	defer os.RemoveAll(work)
	cl, err := newProcessCluster(binary, release, work, r.art.Evidence)
	if err != nil {
		return r.wrap(err)
	}
	defer cl.cleanup()
	r.cluster = cl.(*processCluster)
	cfg := cl.installConfig()
	if err = config.Validate(cfg); err != nil {
		return r.wrap(err)
	}
	files, err := config.NodeConfigs(cfg)
	if err != nil {
		return r.wrap(err)
	}
	r.canary = "deletion_cluster_canary_" + strings.ReplaceAll(model.NewID().String(), "-", "")

	r.enter("dc_bootstrap_and_seed")
	fx, seed, err := cl.bootstrap(r.art.Evidence)
	if err != nil {
		return r.wrap(err)
	}
	r.fx = fx
	if err = cl.provision(files, seed); err != nil {
		return r.wrap(err)
	}

	r.enter("dc_start_three_members")
	if err = cl.start(1, 2, 3); err != nil {
		return r.wrap(err)
	}
	if err = r.refreshSites(1, 2, 3); err != nil {
		return err
	}
	r.enter("dc_ready_all")
	if err = r.ready(240*time.Second, 1, 2, 3); err != nil {
		return err
	}
	r.mark("cluster_ready_ms")
	for _, id := range []uint64{1, 2, 3} {
		if err = r.login(id); err != nil {
			return err
		}
	}

	// ---- ingest the canary through node 1 ----
	r.enter("dc_ingest_canary_through_node_1")
	r.fx.queryTime = fmt.Sprint(time.Now().Add(time.Minute).UnixNano())
	resource := model.Resource{Service: fx.service, Environment: fx.environment, Build: fx.build, Instance: "instance", Labels: model.Labels{}}
	for i := 1; i <= dcBatches; i++ {
		value := model.FloatBits(math.Float64bits(float64(i)))
		record := model.Record{ID: model.NewID(), Kind: model.Metric, ObservedAt: model.UnixNano(time.Now().Add(-time.Duration(dcBatches-i) * time.Second).UnixNano()), Resource: resource,
			Payload: model.Payload{Metric: &model.MetricPoint{Name: r.canary, Labels: model.Labels{}, SampleKind: "float", Value: &value, Unit: "1", Type: "gauge"}}}
		batch := model.Batch{Version: 1, Project: fx.project, Source: fx.source, Producer: model.NewID(), ID: model.NewID(), PolicyRevision: 1, Records: []model.Record{record}}
		if batch.RouteSlot, err = model.OwnerSlot(fx.org, fx.project, fx.source, batch.Producer, record); err != nil {
			return r.wrap(err)
		}
		status, raw, _, err := retryIngest(r.sites[1], batch, fx.credential, 120*time.Second)
		if err != nil || status != 200 {
			return r.wrap(requireSmokeResponse("ingest_canary", status, 200, raw, err))
		}
	}
	r.mark("ingest_done_ms")
	if err = r.check("ingest_acknowledged", true, strconv.Itoa(dcBatches)+" batches acknowledged through node 1"); err != nil {
		return err
	}
	for _, id := range []uint64{1, 2, 3} {
		var body []byte
		err = r.until("canary_served_node_"+strconv.FormatUint(id, 10), 120*time.Second, time.Second, func() (bool, string, error) {
			status, raw, err := r.query(id)
			if err != nil {
				return false, "transport", nil
			}
			body = raw
			return dcServedLatest(status, raw, dcBatches), "status_" + strconv.Itoa(status), nil
		})
		if err != nil {
			return err
		}
		if err = r.check("canary_served_node_"+strconv.FormatUint(id, 10), bytes.Contains(body, []byte(r.canary)), "complete answer with the latest value; the canary name is in the body"); err != nil {
			return err
		}
	}

	// ---- positive control: the canary is physically present on every node ----
	r.enter("dc_positive_control_live_scan")
	control := map[string]dcScan{}
	for _, id := range []uint64{1, 2, 3} {
		s, err := r.scan(id)
		if err != nil {
			return err
		}
		control[strconv.FormatUint(id, 10)] = s
		if err = r.check("positive_control_canary_present_node_"+strconv.FormatUint(id, 10), s.Hits > 0, fmt.Sprintf("%d hits in %d files, by store %v", s.Hits, s.Files, s.ByStore)); err != nil {
			return err
		}
	}
	r.art.Evidence["live_scan_before_deletion"] = control

	// ---- node 3 down, deletion through node 1 ----
	r.enter("dc_kill_node_3")
	if err = cl.kill(3); err != nil {
		return r.wrap(err)
	}
	r.mark("node_3_killed_ms")
	if err = r.ready(120*time.Second, 1, 2); err != nil {
		return err
	}
	if err = r.login(1); err != nil { // fresh reauthentication: a deletion needs a session younger than 5 minutes
		return err
	}
	r.enter("dc_begin_deletion_node_3_down")
	var receipt httpapi.DeletionReceipt
	command := model.NewID()
	err = r.until("begin_deletion", 90*time.Second, time.Second, func() (bool, string, error) {
		status, raw, err := r.ownerSite[1].post("/api/v1/admin/read", struct {
			Kind string `json:"kind"`
		}{"organizations"}, r.owner[1].CSRF, "")
		if err != nil || status != 200 {
			return false, "admin_read_" + strconv.Itoa(status), nil
		}
		var view auth.AdminView
		if err = json.Unmarshal(raw, &view); err != nil {
			return false, "", err
		}
		status, raw, err = r.ownerSite[1].post("/api/v1/admin/deletions", httpapi.DeletionRequest{CommandID: command, ExpectedRevision: model.Uint64(view.Revision), Mode: model.DeleteRetireProject,
			OrgID: fx.org, ProjectIDs: []model.ID{fx.project}, Reason: "deletion-cluster smoke"}, r.owner[1].CSRF, "")
		if err != nil {
			return false, "transport", nil
		}
		switch status {
		case http.StatusAccepted:
			return true, "accepted", json.Unmarshal(raw, &receipt)
		case http.StatusConflict:
			var refused httpapi.DeletionRefused
			if json.Unmarshal(raw, &refused) == nil && refused.Detail != "" {
				return false, "", httpSmokeFailure("begin_deletion", status, http.StatusAccepted, raw)
			}
			return false, "stale_revision", nil // the revision moved between the read and the commit: read again
		case http.StatusServiceUnavailable:
			return false, "status_503", nil
		default:
			return false, "", httpSmokeFailure("begin_deletion", status, http.StatusAccepted, raw)
		}
	})
	if err != nil {
		return err
	}
	r.op = receipt.OperationID
	r.mark("deletion_begun_ms")
	if err = r.check("begin_answers_fencing_202", receipt.Phase == model.DeletePhaseFencing && receipt.Mode == model.DeleteRetireProject, "phase "+safeToken(receipt.Phase)+" mode "+safeToken(receipt.Mode)); err != nil {
		return err
	}
	status, raw, qerr := r.query(1)
	if qerr != nil {
		return r.wrap(qerr)
	}
	if err = r.check("reads_denied_at_begin_node_1", dcDenied(status, raw) && !bytes.Contains(raw, []byte(r.canary)), fmt.Sprintf("status %d code %s", status, dcFaultCode(raw))); err != nil {
		return err
	}

	r.enter("dc_wait_complete_node_3_down")
	complete := map[uint64]httpapi.LifecycleOperation{}
	for _, id := range []uint64{1, 2} {
		if id == 2 {
			if err = r.login(2); err != nil {
				return err
			}
		}
		err = r.until("operation_complete_node_"+strconv.FormatUint(id, 10), r.wait, dcPollInterval, func() (bool, string, error) {
			op, err := r.poll(id)
			if err != nil {
				var sf *smokeFailure
				if errors.As(err, &sf) && sf.Actual >= 500 {
					return false, "status_" + strconv.Itoa(sf.Actual), nil
				}
				return false, "", err
			}
			complete[id] = op
			return op.Phase == model.DeletePhaseComplete && op.Physical == "done", "phase_" + safeToken(op.Phase) + "_physical_" + safeToken(op.Physical), nil
		})
		if err != nil {
			return err
		}
		r.mark("complete_seen_node_" + strconv.FormatUint(id, 10) + "_ms")
	}
	if err = r.check("operation_complete_while_node_3_down", true, "phase complete and physical done on nodes 1 and 2"); err != nil {
		return err
	}

	r.enter("dc_receipt_names_data_apply_db_node_3_down")
	samples := map[string]int{}
	seen := map[string][]string{}
	holdUntil := time.Now().Add(r.hold)
	for first := true; first || time.Now().Before(holdUntil); first = false {
		for _, id := range []uint64{1, 2} {
			op, err := r.poll(id)
			if err != nil {
				return r.wrap(err)
			}
			key := strconv.FormatUint(id, 10)
			samples[key]++
			seen[key] = op.ResidualStores
			ok := op.Phase == model.DeletePhaseComplete && op.Physical == "done" && dcNamesApplyDB(op.ResidualStores)
			if err = r.check("receipt_names_data_apply_db_node_"+key+"_while_node_3_down", ok, fmt.Sprintf("sample %d: phase %s physical %s residual %v", samples[key], safeToken(op.Phase), safeToken(op.Physical), op.ResidualStores)); err != nil {
				return err
			}
		}
		if time.Now().Before(holdUntil) {
			time.Sleep(dcPollInterval)
		}
	}
	r.art.Evidence["receipt_while_node_3_down"] = map[string]any{"samples": samples, "last_residual_stores": seen}
	r.mark("node_3_down_receipt_checked_ms")
	liveDown := map[string]dcScan{}
	for _, id := range []uint64{1, 2} { // informational: the receipt is conservative, this is what the files held
		s, err := r.scan(id)
		if err != nil {
			return err
		}
		liveDown[strconv.FormatUint(id, 10)] = s
	}
	r.art.Evidence["live_scan_node_1_2_while_node_3_down_informational"] = liveDown

	// ---- node 3 back: every receipt clean ----
	r.enter("dc_restart_node_3")
	if err = cl.start(3); err != nil {
		return r.wrap(err)
	}
	r.mark("node_3_restarted_ms")
	if err = r.refreshSites(3); err != nil {
		return err
	}
	if err = r.ready(240*time.Second, 3); err != nil {
		return err
	}
	r.mark("node_3_ready_ms")
	if err = r.login(3); err != nil {
		return err
	}
	r.enter("dc_wait_receipt_clean_all_nodes")
	cleanAt := map[uint64]int64{}
	liveClean := map[string]dcScan{}
	trail := map[string][]string{} // per node: each distinct residual set seen, in order
	err = r.until("receipt_clean_all_nodes", r.wait, dcPollInterval, func() (bool, string, error) {
		progress := make([]string, 0, 3)
		for _, id := range []uint64{1, 2, 3} {
			op, err := r.poll(id)
			if err != nil {
				var sf *smokeFailure
				if errors.As(err, &sf) && sf.Actual >= 500 {
					progress = append(progress, strconv.FormatUint(id, 10)+":status_"+strconv.Itoa(sf.Actual))
					continue
				}
				return false, "", err
			}
			key := strconv.FormatUint(id, 10)
			if seen := strings.Join(op.ResidualStores, "+"); len(trail[key]) == 0 || trail[key][len(trail[key])-1] != "["+seen+"]" {
				trail[key] = append(trail[key], "["+seen+"]")
			}
			clean := op.Phase == model.DeletePhaseComplete && op.Physical == "done" && len(op.ResidualStores) == 0
			if clean && cleanAt[id] == 0 {
				cleanAt[id] = r.since()
				r.mark("receipt_first_clean_node_" + key + "_ms")
				s, err := r.scan(id)
				if err != nil {
					return false, "", err
				}
				liveClean[key] = s
			}
			if !clean {
				progress = append(progress, key+":"+strings.Join(op.ResidualStores, "+"))
			}
		}
		return len(cleanAt) == 3 && len(progress) == 0, "not_clean " + strings.Join(progress, " "), nil
	})
	if err != nil {
		return err
	}
	r.art.Evidence["live_scan_at_first_clean_receipt"] = liveClean
	r.art.Evidence["receipt_residual_trail_after_node_3_restart"] = trail
	if err = r.check("receipt_clean_on_all_three_nodes", true, "phase complete, physical done, no residual store on nodes 1, 2 and 3"); err != nil {
		return err
	}
	for _, id := range []uint64{1, 2, 3} {
		key := strconv.FormatUint(id, 10)
		if err = r.check("live_scan_zero_when_receipt_first_clean_node_"+key, liveClean[key].Hits == 0, fmt.Sprintf("%d hits in %d files, by store %v", liveClean[key].Hits, liveClean[key].Files, liveClean[key].ByStore)); err != nil {
			return err
		}
	}

	// ---- stop every node and scan the whole data directories ----
	r.enter("dc_stop_all_nodes")
	if err = cl.stop(r.art.Evidence); err != nil {
		return r.wrap(err)
	}
	r.mark("all_stopped_ms")
	if err = r.scanAll("stopped_scan", "dc_scan_stopped_data_directories"); err != nil {
		return err
	}

	// ---- restart: denied through each node, still clean, still zero ----
	r.enter("dc_restart_all_nodes")
	if err = cl.start(1, 2, 3); err != nil {
		return r.wrap(err)
	}
	if err = r.refreshSites(1, 2, 3); err != nil {
		return err
	}
	if err = r.ready(240*time.Second, 1, 2, 3); err != nil {
		return err
	}
	r.mark("all_restarted_ready_ms")
	for _, id := range []uint64{1, 2, 3} {
		if err = r.login(id); err != nil {
			return err
		}
	}
	r.enter("dc_denied_through_every_node")
	denied := map[string]any{}
	for _, id := range []uint64{1, 2, 3} {
		key := strconv.FormatUint(id, 10)
		status, raw, err := r.query(id)
		if err != nil {
			return r.wrap(err)
		}
		if err = r.check("read_denied_after_restart_node_"+key, dcDenied(status, raw) && !bytes.Contains(raw, []byte(r.canary)), fmt.Sprintf("status %d code %s", status, dcFaultCode(raw))); err != nil {
			return err
		}
		batch := r.freshBatch()
		istatus, iraw, err := r.sites[id].ingest(batch, fx.credential)
		if err != nil {
			return r.wrap(err)
		}
		if err = r.check("ingest_denied_after_restart_node_"+key, istatus >= 400 && istatus < 500, fmt.Sprintf("status %d code %s", istatus, dcFaultCode(iraw))); err != nil {
			return err
		}
		op, err := r.poll(id)
		if err != nil {
			return r.wrap(err)
		}
		if err = r.check("receipt_still_clean_after_restart_node_"+key, op.Phase == model.DeletePhaseComplete && op.Physical == "done" && len(op.ResidualStores) == 0, fmt.Sprintf("phase %s physical %s residual %v", safeToken(op.Phase), safeToken(op.Physical), op.ResidualStores)); err != nil {
			return err
		}
		denied[key] = map[string]any{"read_status": status, "read_code": dcFaultCode(raw), "ingest_status": istatus, "ingest_code": dcFaultCode(iraw)}
	}
	r.art.Evidence["denied_after_restart"] = denied
	r.enter("dc_stop_final")
	if err = cl.stop(r.art.Evidence); err != nil {
		return r.wrap(err)
	}
	if err = r.scanAll("stopped_scan_after_restart", "dc_scan_after_restart"); err != nil {
		return err
	}
	r.art.Evidence["scenario_wall_clock_ms"] = time.Since(started).Milliseconds()
	return nil
}

// scanAll scans every node's data directory (the processes are stopped) and requires zero
// hits on each; the per-node result is kept in the artifact either way.
func (r *dcRun) scanAll(evidence, stage string) error {
	r.enter(stage)
	results := map[string]dcScan{}
	ids := []uint64{1, 2, 3}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
	var failed error
	for _, id := range ids {
		s, err := r.scan(id)
		if err != nil {
			return err
		}
		key := strconv.FormatUint(id, 10)
		results[key] = s
		detail := fmt.Sprintf("%d hits in %d files (%d bytes); by store %v; files %v", s.Hits, s.Files, s.Bytes, s.ByStore, s.HitFiles)
		if err = r.check(evidence+"_zero_hits_node_"+key, s.Hits == 0, detail); err != nil && failed == nil {
			failed = err
		}
	}
	r.art.Evidence[evidence] = results
	return failed
}

// freshBatch is a well-formed batch for the retired project, never acknowledged.
func (r *dcRun) freshBatch() model.Batch {
	fx := r.fx
	value := model.FloatBits(math.Float64bits(99))
	record := model.Record{ID: model.NewID(), Kind: model.Metric, ObservedAt: model.UnixNano(time.Now().UnixNano()), Resource: model.Resource{Service: fx.service, Environment: fx.environment, Build: fx.build, Instance: "instance", Labels: model.Labels{}},
		Payload: model.Payload{Metric: &model.MetricPoint{Name: r.canary, Labels: model.Labels{}, SampleKind: "float", Value: &value, Unit: "1", Type: "gauge"}}}
	batch := model.Batch{Version: 1, Project: fx.project, Source: fx.source, Producer: model.NewID(), ID: model.NewID(), PolicyRevision: 1, Records: []model.Record{record}}
	batch.RouteSlot, _ = model.OwnerSlot(fx.org, fx.project, fx.source, batch.Producer, record)
	return batch
}

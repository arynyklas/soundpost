func (c *processCluster) stop(report map[string]any) error {
	for id := range c.cmds {
		cmd, done := c.cmds[id], c.done[id]
		if err := cmd.Process.Signal(syscall.SIGTERM); err != nil {
			return err
		}
		select {
		case <-done:
		case <-time.After(30 * time.Second):
			_ = cmd.Process.Kill()
			<-done
			return &smokeFailure{Stage: "graceful_stop", Code: "timeout"}
		}
	}
	c.cmds = map[uint64]*exec.Cmd{}
	report["graceful_stop_all_members"] = true
	return nil
}

func (c *processCluster) checkPrivate(report map[string]any) error {
	entries := 0
	for _, dir := range c.data {
		err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			info, err := d.Info()
			if err != nil {
				return err
			}
			if info.Mode().Perm()&0o077 != 0 {
				return &smokeFailure{Stage: "private_modes", Code: "group_or_other_access"}
			}
			entries++
			return nil
		})
		if err != nil {
			return err
		}
	}
	report["private_mode_entries_checked"] = entries
	return nil
}


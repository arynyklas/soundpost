// RunInstallDistributed starts the PRODUCED distribution as a real three-member cluster and
// drives it over its public HTTPS API:
//
//   - --binary PATH: three real processes of the static binary, one data directory each;
//   - --container IMAGE: three real containers of the image built from deploy/Dockerfile,
//     started by deploy/compose.distributed.yaml (named volumes, read-only configuration).
//
// The cluster configuration is generated by internal/config (the typed InstallConfig), never
// hand-written. Phases: bootstrap a single installation and export its seed; start three
// members; wait for /readyz; ingest through the initial leader and query through a follower;
// kill the initial leader (writes must still commit through another member), restart it and
// require it to rejoin and converge; kill two members (quorum loss) and require a typed
// not-ready refusal with no acknowledgement; restart and converge again. It also exercises the
// off-host backup authority gate of internal/config against the real internal/backup authority
// on a local directory, and (with a container image) the permission separation of the native
// helper at runtime.
//
// Registered as: case "install-distributed": return RunInstallDistributed(os.Args[2:]).
func RunInstallDistributed(args []string) (result error) {
	stage := "dist_flags"
	defer func() { result = annotateSmokeFailure("install_distributed", stage, model.ID{}, result) }()
	f := flag.NewFlagSet("install-distributed", flag.ContinueOnError)
	f.SetOutput(io.Discard)
	artifact := f.String("artifact-dir", "", "sanitized result directory")
	binary := f.String("binary", "", "produced static soundpost binary (three processes)")
	release := f.String("release", "", "release directory the binary must belong to")
	container := f.String("container", "", "image built from deploy/Dockerfile (three containers via deploy/compose.distributed.yaml)")
	composeFile := f.String("compose", "deploy/compose.distributed.yaml", "Compose file (container mode)")
	probeImage := f.String("perf-probe-image", "", "image whose entrypoint the native-permission probe replaces (default: --container)")
	if err := f.Parse(args); err != nil {
		return err
	}
	if *artifact == "" || (*binary == "") == (*container == "") {
		return errors.New("--artifact-dir and exactly one of --binary or --container are required")
	}
	if err := os.MkdirAll(*artifact, 0o700); err != nil {
		return err
	}
	if *probeImage == "" {
		*probeImage = *container
	}
	report := map[string]any{"version": 1, "caveat": "local-process/container simulation on one host: NOT three physical failure domains, no power-loss or distinct-hardware qualification"}
	started := time.Now()

	stage = "dist_pki_and_layout"
	work, err := os.MkdirTemp("", "soundpost-dist-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(work)
	var cluster distCluster
	if *binary != "" {
		report["mode"] = "three_processes"
		cluster, err = newProcessCluster(*binary, *release, work, report)
	} else {
		report["mode"] = "three_containers_compose"
		cluster, err = newComposeCluster(*container, *composeFile, work, report)
	}
	if err != nil {
		return err
	}
	defer cluster.cleanup()
	if err = cluster.describeHost(report); err != nil {
		return err
	}

	stage = "dist_typed_config"
	cfg := cluster.installConfig()
	if err = config.Validate(cfg); err != nil {
		return err
	}
	files, err := config.NodeConfigs(cfg)
	if err != nil {
		return err
	}
	report["config_summary"], report["config_qualification"] = cfg.Summary(), config.Qualification(cfg)
	report["node_files_generated_by_internal_config"] = len(files)

	stage = "dist_bootstrap_and_seed"
	fx, seed, err := cluster.bootstrap(report)
	if err != nil {
		return err
	}
	if err = cluster.provision(files, seed); err != nil {
		return err
	}

	stage = "dist_start_three_members"
	nodes := cluster.nodes()
	if err = cluster.start(1, 2, 3); err != nil {
		return err
	}
	sites := map[uint64]*installSite{}
	for _, n := range nodes {
		if sites[n.id], err = cluster.site(n.id); err != nil {
			return err
		}
	}
	stage = "dist_ready_all"
	for _, n := range nodes {
		if err = waitNodeReady(sites[n.id], 180*time.Second); err != nil {
			return err
		}
	}
	if err = cluster.health(report); err != nil {
		return err
	}
	report["ready_after_s"] = time.Since(started).Round(time.Second).Seconds()
	// Each member has its own reader session (cookie jar and CSRF token).
	sessions := map[uint64]auth.Session{}
	login := func(id uint64) error {
		s, err := loginReader(sites[id], fx)
		sessions[id] = s
		return err
	}
	nfx := func(id uint64) *installFixture {
		c := *fx
		c.reader = sessions[id]
		return &c
	}

	// ---- ingest through the initial leader, query through a follower ----
	stage = "dist_ingest_leader"
	if err = login(1); err != nil {
		return err
	}
	ledger := &distLedger{}
	if err = ledger.write(sites[1], fx, "leader_a"); err != nil {
		return err
	}
	stage = "dist_query_follower"
	fx.queryTime = fmt.Sprint(time.Now().Add(time.Minute).UnixNano())
	answers := map[uint64][]byte{}
	for _, id := range []uint64{2, 3, 1} {
		if err = login(id); err != nil {
			return err
		}
		if answers[id], err = eventuallyQuery(sites[id], nfx(id), ledger, 60*time.Second); err != nil {
			return err
		}
	}
	if !bytes.Equal(answers[1], answers[2]) || !bytes.Equal(answers[2], answers[3]) {
		return &smokeFailure{Stage: stage, Code: "members_answer_differently"}
	}
	report["query_same_on_leader_and_followers"] = true

	stage = "dist_ingest_follower"
	if err = ledger.write(sites[2], fx, "follower_b"); err != nil {
		return err
	}
	for _, id := range []uint64{1, 3, 2} {
		if _, err = eventuallyQuery(sites[id], nfx(id), ledger, 60*time.Second); err != nil {
			return err
		}
	}
	report["write_through_follower_visible_everywhere"] = true

	// ---- one member lost: writes still commit ----
	stage = "dist_kill_initial_leader"
	if err = cluster.kill(1); err != nil {
		return err
	}
	killedAt := time.Now()
	if err = ledger.write(sites[2], fx, "after_kill_via_b"); err != nil {
		return err
	}
	report["first_ack_after_kill_s"] = time.Since(killedAt).Round(100 * time.Millisecond).Seconds()
	report["statuses_seen_before_first_ack"] = ledger.lastStatuses
	if _, err = eventuallyQuery(sites[3], nfx(3), ledger, 60*time.Second); err != nil {
		return err
	}
	for _, id := range []uint64{2, 3} {
		if err = waitNodeReady(sites[id], 60*time.Second); err != nil {
			return err
		}
	}
	report["writes_commit_with_one_member_down"] = true

	stage = "dist_rejoin_converge"
	if err = cluster.start(1); err != nil {
		return err
	}
	if sites[1], err = cluster.site(1); err != nil {
		return err
	}
	if err = waitNodeReady(sites[1], 180*time.Second); err != nil {
		return err
	}
	if err = login(1); err != nil {
		return err
	}
	if answers[1], err = eventuallyQuery(sites[1], nfx(1), ledger, 90*time.Second); err != nil {
		return err
	}
	if cursors, err := converged(sites, 90*time.Second); err != nil {
		return err
	} else {
		report["control_applied_cursor_equal_on_all_members"] = cursors
	}
	report["killed_member_rejoined_and_converged"] = true

	// ---- the documented rolling order: each remaining member, one at a time, gated on readiness ----
	stage = "dist_rolling_restart"
	rolling := map[string]any{}
	for _, step := range []struct{ id, via uint64 }{{3, 1}, {2, 3}} {
		if err = cluster.kill(step.id); err != nil {
			return err
		}
		killed := time.Now()
		if err = ledger.write(sites[step.via], fx, "rolling_"+strconv.FormatUint(step.id, 10)); err != nil {
			return err
		}
		rolling["first_ack_s_member_"+strconv.FormatUint(step.id, 10)+"_down"] = time.Since(killed).Round(100 * time.Millisecond).Seconds()
		if err = cluster.start(step.id); err != nil {
			return err
		}
		if sites[step.id], err = cluster.site(step.id); err != nil {
			return err
		}
		if err = waitNodeReady(sites[step.id], 180*time.Second); err != nil {
			return err
		}
		if err = login(step.id); err != nil {
			return err
		}
		for _, id := range []uint64{1, 2, 3} {
			if _, err = eventuallyQuery(sites[id], nfx(id), ledger, 90*time.Second); err != nil {
				return err
			}
		}
		if _, err = converged(sites, 90*time.Second); err != nil {
			return err
		}
	}
	report["rolling_restart_one_member_at_a_time"] = rolling

	// ---- quorum loss: two members down, one survivor ----
	stage = "dist_quorum_loss"
	for _, id := range []uint64{2, 3} {
		if err = cluster.kill(id); err != nil {
			return err
		}
	}
	reason, lastSeen := "", "none"
	deadline := time.Now().Add(90 * time.Second)
	for time.Now().Before(deadline) {
		code, raw, err := sites[1].get("/readyz")
		if err != nil {
			lastSeen = "transport"
		} else {
			var st installReadiness
			_ = json.Unmarshal(raw, &st)
			lastSeen = strconv.Itoa(code) + "_" + safeToken(st.Reason)
			if code == 503 && (st.Reason == "no_quorum" || st.Reason == "state_unavailable") {
				reason = st.Reason
				break
			}
		}
		time.Sleep(500 * time.Millisecond)
	}
	// The decision function reports no_quorum when a ReadIndex round fails inside the 3 s
	// evaluation bound and state_unavailable when the bound itself elapses first; both are the
	// closed 503 not-ready answer and neither is ever 200.
	if reason == "" {
		return &smokeFailure{Stage: stage, Code: "survivor_never_reported_not_ready_last_" + lastSeen}
	}
	report["survivor_readyz_reason"] = reason
	stage = "dist_quorum_loss_refuses_ack"
	slow := withTimeout(sites[1], 70*time.Second)
	batch := ledger.next(fx, "during_quorum_loss")
	began := time.Now()
	status, raw, err := slow.ingest(batch, fx.credential)
	refusal := map[string]any{"after_s": time.Since(began).Round(100 * time.Millisecond).Seconds()}
	switch {
	case err != nil:
		// a client-side deadline is not an acknowledgement, but it is not a typed refusal either
		return &smokeFailure{Stage: stage, Code: "no_typed_refusal_before_client_deadline"}
	case status == 200:
		return &smokeFailure{Stage: stage, Code: "acknowledged_without_quorum"}
	case status != 503:
		return httpSmokeFailure("quorum_loss_ingest", status, 503, raw)
	}
	var fault struct {
		Code      string `json:"code"`
		Retryable bool   `json:"retryable"`
	}
	if json.Unmarshal(raw, &fault) != nil || !(fault.Code == "unavailable" || fault.Code == "stale" || fault.Code == "timeout") || !fault.Retryable || bytes.Contains(raw, []byte(`"cursor"`)) {
		return &smokeFailure{Stage: stage, Code: "refusal_not_typed_not_ready"}
	}
	refusal["status"], refusal["code"], refusal["retryable"] = status, fault.Code, fault.Retryable
	report["quorum_loss_ingest"] = refusal
	// A read on the minority must not be served as a complete current answer.
	qstatus, qraw, qerr := queryExpr(withTimeout(sites[1], 70*time.Second), nfx(1), "distributed_smoke_writes")
	if qerr == nil && qstatus == 200 {
		var result query.Result
		if json.Unmarshal(qraw, &result) == nil && len(result.Projects) == 1 && result.Projects[0].Failure == nil && result.Projects[0].Completeness == query.CompletenessComplete {
			return &smokeFailure{Stage: stage, Code: "minority_served_a_complete_read"}
		}
	}
	report["quorum_loss_query_status"] = qstatus
	var qfault struct {
		Code string `json:"code"`
	}
	if json.Unmarshal(qraw, &qfault) == nil {
		report["quorum_loss_query_code"] = safeToken(qfault.Code)
	}
	report["no_silent_local_ack"] = true

	stage = "dist_recover_after_quorum_loss"
	if err = cluster.start(2, 3); err != nil {
		return err
	}
	for _, id := range []uint64{2, 3} {
		if sites[id], err = cluster.site(id); err != nil {
			return err
		}
	}
	for _, id := range []uint64{1, 2, 3} {
		if err = waitNodeReady(sites[id], 240*time.Second); err != nil {
			return err
		}
	}
	// The refused batch is retried unchanged: it commits now (or already had) and is acknowledged once.
	rstatus, rraw, _, err := retryIngest(sites[2], batch, fx.credential, 120*time.Second)
	if err != nil || rstatus != 200 {
		return httpSmokeFailure("retry_after_recovery", rstatus, 200, rraw)
	}
	ledger.accept(batch)
	for _, id := range []uint64{1, 2, 3} {
		if err = login(id); err != nil {
			return err
		}
		if answers[id], err = eventuallyQuery(sites[id], nfx(id), ledger, 90*time.Second); err != nil {
			return err
		}
	}
	if !bytes.Equal(answers[1], answers[2]) || !bytes.Equal(answers[2], answers[3]) {
		return &smokeFailure{Stage: stage, Code: "members_answer_differently_after_recovery"}
	}
	if cursors, err := converged(sites, 90*time.Second); err != nil {
		return err
	} else {
		report["control_applied_cursor_after_recovery"] = cursors
	}
	report["acknowledged_batches"] = len(ledger.accepted)
	report["recovered_after_quorum_loss"] = true

	stage = "dist_stop_private_modes_logs"
	if err = cluster.stop(report); err != nil {
		return err
	}
	if err = cluster.checkPrivate(report); err != nil {
		return err
	}
	if err = cluster.checkLogs([]string{fx.credential, fx.password, "install smoke reader password 2026", fx.session.Token, fx.session.CSRF, fx.reader.Token, fx.reader.CSRF}, cluster.keyMaterial()); err != nil {
		return err
	}
	report["server_logs_free_of_credentials_and_private_keys"] = true

	stage = "dist_backup_authority_gate"
	if err = backupAuthorityDrill(cfg, work, report); err != nil {
		return err
	}
	stage = "dist_native_permission_runtime"
	if err = nativePermissionRuntime(*probeImage, *composeFile, work, report); err != nil {
		return err
	}

	report["wall_clock_s"] = time.Since(started).Round(time.Second).Seconds()
	report["not_run"] = []string{
		"authorized isolated Kubernetes cluster (the chart is only rendered and statically checked)",
		"three independent physical hosts, disks, power or network paths",
		"restore of a backup into a three-voter cluster (not implemented; docs/operations/backup-restore.md) - the single-node backup-restore smoke is separate",
		"the optional native helper image (not produced) and kernel 6.1 / arm64",
	}
	stage = "dist_artifact"
	encoded, _ := json.MarshalIndent(report, "", "  ")
	return os.WriteFile(filepath.Join(*artifact, "install-distributed.json"), encoded, 0o600)
}

// ---- the cluster abstraction ----

type distNode struct {
	id       uint64
	name     string // a, b, c
	identity string
}

type distCluster interface {
	nodes() []distNode
	installConfig() config.InstallConfig
	describeHost(report map[string]any) error
	bootstrap(report map[string]any) (*installFixture, []byte, error)
	provision(files map[uint64][]byte, seed []byte) error
	start(ids ...uint64) error
	kill(id uint64) error
	site(id uint64) (*installSite, error)
	health(report map[string]any) error
	stop(report map[string]any) error
	checkPrivate(report map[string]any) error
	checkLogs(secrets []string, keys []string) error
	keyMaterial() []string
	cleanup()
}

var distNodes = []distNode{{1, "a", "node-a"}, {2, "b", "node-b"}, {3, "c", "node-c"}}

// distPKI writes a throwaway cluster CA and one certificate per member. Each certificate
// carries the member's URI SAN spiffe://soundpost/node/<identity> and its dial names.
func distPKI(dir string, sans map[uint64][]string, ips []net.IP) (ca string, certs, keys map[uint64]string, material []string, err error) {
	caKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return
	}
	now := time.Now()
	authority := &x509.Certificate{SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: "Soundpost distributed smoke CA"}, NotBefore: now.Add(-time.Minute), NotAfter: now.Add(6 * time.Hour), IsCA: true, BasicConstraintsValid: true, KeyUsage: x509.KeyUsageCertSign | x509.KeyUsageDigitalSignature}
	der, err := x509.CreateCertificate(rand.Reader, authority, authority, &caKey.PublicKey, caKey)
	if err != nil {
		return
	}
	ca = filepath.Join(dir, "ca.pem")
	if err = os.WriteFile(ca, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o600); err != nil {
		return
	}
	certs, keys = map[uint64]string{}, map[uint64]string{}
	for _, n := range distNodes {
		var private *ecdsa.PrivateKey
		if private, err = ecdsa.GenerateKey(elliptic.P256(), rand.Reader); err != nil {
			return
		}
		identity, _ := url.Parse("spiffe://soundpost/node/" + n.identity)
		leaf := &x509.Certificate{SerialNumber: big.NewInt(int64(n.id + 1)), Subject: pkix.Name{CommonName: "generic fixture node"}, NotBefore: now.Add(-time.Minute), NotAfter: now.Add(6 * time.Hour), DNSNames: sans[n.id], IPAddresses: ips, URIs: []*url.URL{identity}, KeyUsage: x509.KeyUsageDigitalSignature, ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth, x509.ExtKeyUsageClientAuth}}
		var raw []byte
		if raw, err = x509.CreateCertificate(rand.Reader, leaf, authority, &private.PublicKey, caKey); err != nil {
			return
		}
		encoded, e := x509.MarshalPKCS8PrivateKey(private)
		if e != nil {
			err = e
			return
		}
		certs[n.id], keys[n.id] = filepath.Join(dir, n.name+".pem"), filepath.Join(dir, n.name+".key")
		keyPEM := pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: encoded})
		if err = os.WriteFile(certs[n.id], pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: raw}), 0o600); err != nil {
			return
		}
		if err = os.WriteFile(keys[n.id], keyPEM, 0o600); err != nil {
			return
		}
		material = append(material, base64Body(keyPEM))
	}
	return
}

func base64Body(p []byte) string {
	b, _ := pem.Decode(p)
	if b == nil || len(b.Bytes) < 48 {
		return ""
	}
	return fmt.Sprintf("%x", b.Bytes[16:40])
}

// ---- helpers shared by both hosts ----

func withTimeout(s *installSite, d time.Duration) *installSite {
	client := *s.client
	client.Timeout = d
	return &installSite{base: s.base, client: &client}
}

func waitNodeReady(site *installSite, limit time.Duration) error {
	deadline := time.Now().Add(limit)
	last := ""
	for time.Now().Before(deadline) {
		code, raw, err := site.get("/readyz")
		if err == nil && code == 200 {
			var st installReadiness
			if json.Unmarshal(raw, &st) == nil && st.Ready {
				return nil
			}
		} else if err == nil {
			var st installReadiness
			_ = json.Unmarshal(raw, &st)
			last = st.Reason
		}
		time.Sleep(300 * time.Millisecond)
	}
	return &smokeFailure{Stage: "member_ready", Code: "timeout_" + safeToken(last)}
}

func safeToken(s string) string {
	if s == "" {
		return "no_answer"
	}
	for _, r := range s {
		if !(r >= 'a' && r <= 'z' || r == '_') {
			return "unknown"
		}
	}
	return s
}

// converged waits until every member reports the same control applied cursor.
func converged(sites map[uint64]*installSite, limit time.Duration) (map[string]uint64, error) {
	deadline := time.Now().Add(limit)
	for time.Now().Before(deadline) {
		seen := map[string]uint64{}
		same, first := true, uint64(0)
		for id, s := range sites {
			code, raw, err := s.get("/readyz")
			var st installReadiness
			if err != nil || code != 200 || json.Unmarshal(raw, &st) != nil || !st.Ready || st.Applied == nil {
				same = false
				break
			}
			seen[strconv.FormatUint(id, 10)] = uint64(st.Applied.Index)
			if first == 0 {
				first = uint64(st.Applied.Index)
			} else if uint64(st.Applied.Index) != first {
				same = false
			}
		}
		if same && len(seen) == len(sites) {
			return seen, nil
		}
		time.Sleep(500 * time.Millisecond)
	}
	return nil, &smokeFailure{Stage: "converge", Code: "applied_cursors_differ"}
}

func loginReader(site *installSite, fx *installFixture) (auth.Session, error) {
	var session auth.Session
	status, raw, err := site.post("/api/v1/login", map[string]string{"Email": fx.readerEmail, "Password": "install smoke reader password 2026", "Code": ""}, "", "")
	if err = requireSmokeResponse("reader_login", status, 200, raw, err); err != nil {
		return session, err
	}
	return session, json.Unmarshal(raw, &session)
}

// distLedger records every acknowledged write so the final query can name the exact latest value.
type distLedger struct {
	accepted     []installReceipt
	sequence     int
	lastStatuses []int
}

// next builds the next batch (one float metric sample whose value is its sequence number).
func (l *distLedger) next(fx *installFixture, label string) model.Batch {
	l.sequence++
	resource := model.Resource{Service: fx.service, Environment: fx.environment, Build: fx.build, Instance: "instance", Labels: model.Labels{}}
	value := model.FloatBits(math.Float64bits(float64(l.sequence)))
	record := model.Record{ID: model.NewID(), Kind: model.Metric, ObservedAt: model.UnixNano(time.Now().UnixNano()), Resource: resource, Payload: model.Payload{Metric: &model.MetricPoint{Name: "distributed_smoke_writes", Labels: model.Labels{}, SampleKind: "float", Value: &value, Unit: "1", Type: "gauge"}}}
	batch := model.Batch{Version: 1, Project: fx.project, Source: fx.source, Producer: model.NewID(), ID: model.NewID(), PolicyRevision: 1, Records: []model.Record{record}}
	batch.RouteSlot, _ = model.OwnerSlot(fx.org, fx.project, fx.source, batch.Producer, record)
	_ = label
	return batch
}

func (l *distLedger) accept(b model.Batch) {
	l.accepted = append(l.accepted, installReceipt{name: "w", batch: b})
}

// write sends one new batch to a member (retrying the SAME batch through an election) and records it.
func (l *distLedger) write(site *installSite, fx *installFixture, label string) error {
	batch := l.next(fx, label)
	status, raw, statuses, err := retryIngest(site, batch, fx.credential, 120*time.Second)
	l.lastStatuses = statuses
	if err != nil || status != 200 {
		return httpSmokeFailure("write_"+label, status, 200, raw)
	}
	var receipt model.Receipt
	if json.Unmarshal(raw, &receipt) != nil || receipt.Cursor.Index == 0 {
		return &smokeFailure{Stage: "write_" + label, Code: "receipt_decode"}
	}
	l.accepted = append(l.accepted, installReceipt{name: label, batch: batch, receipt: receipt})
	return nil
}

// retryIngest posts one batch until it is acknowledged. Only 503 (retryable, typed) and a
// refused connection may be retried; anything else is returned at once. The batch is
// identical on every attempt, so a retry can never double-write. It also returns the
// retryable statuses seen on the way.
func retryIngest(site *installSite, batch model.Batch, credential string, limit time.Duration) (int, []byte, []int, error) {
	deadline := time.Now().Add(limit)
	var seen []int
	for {
		status, raw, err := site.ingest(batch, credential)
		if err == nil && (status == 200 || status != 503) {
			return status, raw, seen, nil
		}
		if err == nil {
			seen = append(seen, status)
		}
		if time.Now().After(deadline) {
			return status, raw, seen, err
		}
		time.Sleep(500 * time.Millisecond)
	}
}

func queryExpr(site *installSite, fx *installFixture, expression string) (int, []byte, error) {
	profile := "promql-prometheus-3.1.0"
	manifest, err := installProfile(profile)
	if err != nil {
		return 0, nil, err
	}
	match := installFeatureSet.FindSubmatch(manifest)
	if match == nil {
		return 0, nil, &smokeFailure{Stage: "query", Code: "feature_set"}
	}
	body := map[string]any{"org": fx.org.String(), "language": "promql", "profile": profile, "feature_set": string(match[1]), "expression": expression,
		"evaluation": map[string]any{"instant": true, "time": fx.queryTime, "start": "0", "end": "0", "step": "0"},
		"projects":   []string{fx.project.String()}, "budget": map[string]any{"timeout_ns": "0", "memory_bytes": "0", "max_returned": "0"}, "allow_partial": false}
	return site.post("/api/v1/query", body, fx.reader.CSRF, "")
}

// eventuallyQuery waits until the member serves a COMPLETE answer whose single sample equals the
// latest acknowledged value, and returns the canonical answer (minus its own execution time).
func eventuallyQuery(site *installSite, fx *installFixture, l *distLedger, limit time.Duration) ([]byte, error) {
	want := float64(l.sequence)
	if n := len(l.accepted); n > 0 {
		want = 0
		for _, a := range l.accepted {
			if v := *a.batch.Records[0].Payload.Metric.Value; math.Float64frombits(uint64(v)) > want {
				want = math.Float64frombits(uint64(v))
			}
		}
	}
	deadline := time.Now().Add(limit)
	last := "no_answer"
	for time.Now().Before(deadline) {
		status, raw, err := queryExpr(site, fx, "distributed_smoke_writes")
		if err == nil && status == 200 {
			var result query.Result
			if json.Unmarshal(raw, &result) == nil && len(result.Projects) == 1 {
				got := result.Projects[0]
				if got.Failure == nil && got.Completeness == query.CompletenessComplete && got.Value != nil && got.Value.Type == query.ValueVector && len(got.Value.Vector) == 1 && got.Value.Vector[0].Sample.Float != nil {
					if math.Float64frombits(uint64(*got.Value.Vector[0].Sample.Float)) == want {
						result.Projects[0].Stats.ElapsedNS = 0
						return json.Marshal(result)
					}
					last = "wrong_value"
				} else {
					last = "incomplete"
				}
			}
		} else if err == nil {
			last = "status_" + strconv.Itoa(status)
		}
		time.Sleep(500 * time.Millisecond)
	}
	return nil, &smokeFailure{Stage: "member_query", Code: "never_served_latest_acknowledged_value_" + last}
}


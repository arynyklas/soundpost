func (c *processCluster) start(ids ...uint64) error {
	for _, id := range ids {
		cmd := exec.Command(c.binary, "serve", "--mode=distributed", "--node-id", strconv.FormatUint(id, 10), "--cluster-config", filepath.Join(c.root, fmt.Sprintf("node-%d.json", id)), "--data-dir", c.data[id], "--listen", c.public[id])
		cmd.Stdout, cmd.Stderr = c.logs[id], c.logs[id]
		cmd.Env = []string{"PATH=" + os.Getenv("PATH")}
		if err := cmd.Start(); err != nil {
			return err
		}
		done := make(chan error, 1)
		go func() { done <- cmd.Wait() }()
		c.mu.Lock()
		c.cmds[id], c.done[id] = cmd, done
		c.mu.Unlock()
	}
	return nil
}

func (c *processCluster) kill(id uint64) error {
	c.mu.Lock()
	cmd, done := c.cmds[id], c.done[id]
	c.mu.Unlock()
	if cmd == nil {
		return errors.New("member not running")
	}
	_ = cmd.Process.Kill()
	<-done
	c.mu.Lock()
	delete(c.cmds, id)
	c.mu.Unlock()
	return nil
}

func (c *processCluster) site(id uint64) (*installSite, error) {
	if c.sites[id] == nil {
		deadline := time.Now().Add(60 * time.Second)
		for c.certs[id] == nil {
			if time.Now().After(deadline) {
				return nil, &smokeFailure{Stage: "member_certificate", Code: "timeout"}
			}
			if raw, err := os.ReadFile(filepath.Join(c.data[id], "server.crt")); err == nil {
				if block, _ := pem.Decode(raw); block != nil {
					c.certs[id], _ = x509.ParseCertificate(block.Bytes)
				}
			}
			time.Sleep(50 * time.Millisecond)
		}
		c.sites[id] = newInstallSite("https://"+c.public[id], c.certs[id])
	}
	deadline := time.Now().Add(60 * time.Second)
	for time.Now().Before(deadline) {
		if conn, err := net.DialTimeout("tcp", c.public[id], time.Second); err == nil {
			conn.Close()
			return c.sites[id], nil
		}
		time.Sleep(50 * time.Millisecond)
	}
	return nil, &smokeFailure{Stage: "member_listen", Code: "timeout"}
}


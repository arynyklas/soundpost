// provision fills each member's configuration volume with ONLY that member's files, owned by
// the container uid and unreadable by anyone else, exactly as docs/operations/distributed.md
// instructs the operator to do.
func (c *composeCluster) provision(files map[uint64][]byte, seed []byte) error {
	caPEM, err := os.ReadFile(c.pki.ca)
	if err != nil {
		return err
	}
	for _, n := range distNodes {
		volume := c.project + "-" + n.name + "-config"
		if _, err := dockerOut("volume", "create", volume); err != nil {
			return err
		}
		certPEM, _ := os.ReadFile(c.pki.certs[n.id])
		keyPEM, _ := os.ReadFile(c.pki.keys[n.id])
		var buf bytes.Buffer
		tw := tar.NewWriter(&buf)
		add := func(name string, mode int64, content []byte, dir bool) {
			h := &tar.Header{Name: name, Mode: mode, Uid: 65532, Gid: 65532, ModTime: time.Now(), Size: int64(len(content)), Typeflag: tar.TypeReg}
			if dir {
				h.Typeflag, h.Size = tar.TypeDir, 0
			}
			_ = tw.WriteHeader(h)
			if !dir {
				_, _ = tw.Write(content)
			}
		}
		add("pki/", 0o500, nil, true)
		add(fmt.Sprintf("node-%d.json", n.id), 0o400, files[n.id], false)
		add("cluster.seed", 0o400, seed, false)
		add("pki/ca.pem", 0o400, caPEM, false)
		add("pki/"+n.name+".pem", 0o400, certPEM, false)
		add("pki/"+n.name+".key", 0o400, keyPEM, false)
		if err = tw.Close(); err != nil {
			return err
		}
		holder := c.project + "-" + n.name + "-fill"
		if _, err = dockerOut("create", "--name", holder, "-v", volume+":/etc/soundpost", c.image); err != nil {
			return err
		}
		cp := exec.Command("docker", "cp", "-", holder+":/etc/soundpost")
		cp.Stdin = &buf
		cpErr := cp.Run()
		_ = exec.Command("docker", "rm", "-f", holder).Run()
		if cpErr != nil {
			return &smokeFailure{Stage: "provision_config_volume", Code: "copy_failed"}
		}
	}
	return nil
}

